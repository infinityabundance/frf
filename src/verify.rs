/// A compiled claim whose identity AND full admission have been re-verified
/// against the evidence tree. Private fields: the only constructor is
/// [`load_claim_verified`], so a `ClaimVerified` cannot be fabricated — a
/// hand-written canonical file at `claims/<id>.json` is REFUSED, not
/// rendered. The renderers accept only this type: data becomes evidence only
/// after verification.
pub struct ClaimVerified {
    id: String,
    claim: crate::model::ClaimRecord,
    premises: Vec<ReceiptVerified>,
}

impl ClaimVerified {
    pub fn id(&self) -> &str {
        &self.id
    }

    pub fn claim(&self) -> &crate::model::ClaimRecord {
        &self.claim
    }

    /// The verified premise receipts (the claim's `requires`, each itself
    /// identity + derivation verified). The renderers derive prose from
    /// THESE — never from anything stored in the claim file.
    pub fn premises(&self) -> &[ReceiptVerified] {
        &self.premises
    }
}

/// Verify one recorded capability entry (per-premise, per-axis challenge
/// coverage) against the evidence: every challenge id must be a
/// content-addressed record of the premise's court wrapping the premise's
/// reference artifact, targeting exactly that axis, whose mutant run
/// answered the same question — and the verdicts (`saw_defect`,
/// `specificity_clean`) must RECOMPUTE from the verified mutant run's
/// residuals. This is the same admission the compiler enforced, re-run
/// against the recorded evidence — never trusted from the claim file.
fn verify_capability_entry(
    store: &Store,
    entry: &crate::model::ClaimCapability,
    premise_id: &str,
    premise: &Receipt,
) -> Result<()> {
    if entry.receipt != premise_id {
        return Err(FrfError::new(format!(
            "claim capability for axis {} binds premise {}, but the premise is {}",
            entry.axis, entry.receipt, premise_id
        )));
    }
    if entry.challenge_ids.is_empty() {
        return Err(FrfError::new(format!(
            "claim capability for axis {} names no challenge",
            entry.axis
        )));
    }
    // The DEMONSTRATED mutation profile rederives from the named challenges:
    // the distinct operators of exactly the recorded challenge ids (a
    // hand-edited or omitted profile is a tampered claim, not evidence).
    let mut rederived_profile: Vec<String> = Vec::new();
    for cid in &entry.challenge_ids {
        let ch = store.load_challenge(cid)?; // content-addressed
        rederived_profile.push(ch.operator.clone());
        if ch.court != premise.court.id {
            return Err(FrfError::new(format!(
                "claim capability: challenge {cid} is not a challenge of premise {}'s court",
                premise_id
            )));
        }
        if ch.target_axis != entry.axis {
            return Err(FrfError::new(format!(
                "claim capability: challenge {cid} targets {} not {}",
                ch.target_axis, entry.axis
            )));
        }
        if ch.reference_sha256 != premise.authority.identity_hash {
            return Err(FrfError::new(format!(
                "claim capability: challenge {cid} does not wrap premise {}'s reference artifact",
                premise_id
            )));
        }
        let mut_cap = load_capture_verified(store, &ch.run)?;
        if mut_cap.capture.court_semantic_identity != premise.court.semantic_identity {
            return Err(FrfError::new(format!(
                "claim capability: challenge {cid} did not run premise {}'s question",
                premise_id
            )));
        }
        // The verdicts recompute from the VERIFIED mutant residuals.
        let mut on_target = false;
        let mut on_unaffected = false;
        for rid in &mut_cap.capture.residuals {
            let rec = load_residual_verified(store, rid)?;
            if rec.record().axis.as_str() == ch.target_axis {
                on_target = true;
            } else {
                on_unaffected = true;
            }
        }
        if !on_target || on_unaffected {
            return Err(FrfError::new(format!(
                "claim capability: challenge {cid} does not demonstrate sensitivity on {} (recomputed: saw_defect={on_target}, specificity_clean={})",
                entry.axis,
                !on_unaffected
            )));
        }
    }
    rederived_profile.sort();
    rederived_profile.dedup();
    if entry.mutation_profile != rederived_profile {
        return Err(FrfError::new(format!(
            "claim capability for axis {}: its recorded mutation profile {:?} does not rederive from the named challenge records ({:?}) — a hand-edited or forged profile is refused",
            entry.axis, entry.mutation_profile, rederived_profile
        )));
    }
    Ok(())
}

/// Verify that a committed knowledge universe U is reproducible WITHIN the
/// current store — the containment direction of claim re-verification. A
/// claim compiled under U stays admissible exactly as long as nothing U named
/// was lost or mutated:
///
/// - every residual head still exists as the exact immutable observation the
///   universe committed (verified load, then the record content address and
///   the fingerprint must rederive to the committed values);
/// - every committed object (receipt/run/authority/series/reduction) still
///   exists and its content address rederives to the committed cid;
/// - the snapshot's own cid rederives from its fields.
///
/// The store may have GROWN since compile time — new runs, new residuals,
/// new series, later disposition events. Those are outside U and do not
/// rewrite the claim: the claim remains a projection of the exact universe it
/// names (a baseline claim compiled early stays renderable after later
/// evidence exists). What is refused is a store that LOST or MUTATED evidence
/// U depended on — recompilation against a fresh universe is the only remedy.
/// The blocker search itself (the negative side) re-runs over the COMMITTED
/// U, not the current store, via [`crate::commands::claim::store_blockers`].
pub fn verify_knowledge_universe(store: &Store, universe: &KnowledgeSnapshot) -> Result<()> {
    // The snapshot's own identity rederives from its fields (defense in
    // depth: the claim's content address already covers these bytes, but the
    // universe must also stand on its own).
    let rederived = crate::semantics::knowledge_snapshot_identity(universe)?;
    if rederived != universe.cid {
        return Err(FrfError::new(format!(
            "the committed knowledge universe's cid does not rederive from its fields ({} != {}) — the universe is not self-authenticating",
            &rederived[..16],
            &universe.cid[..16]
        )));
    }

    // Every residual head: the exact immutable observation still exists and
    // still matches the committed record content address and fingerprint.
    for head in &universe.residual_heads {
        let verified = load_residual_verified(store, &head.id).map_err(|e| {
            FrfError::new(format!(
                "the committed knowledge universe names residual {} but it is not verifiable evidence in this store: {e}",
                head.id
            ))
        })?;
        let record_cid = crate::semantics::record_content_identity(verified.record())?;
        if record_cid != head.record_cid {
            return Err(FrfError::new(format!(
                "residual {} no longer matches the committed knowledge universe: its record content address rederives to {} but the universe committed {} — a store that mutated evidence the claim names cannot re-verify it",
                head.id,
                &record_cid[..16],
                &head.record_cid[..16]
            )));
        }
        let fingerprint = crate::semantics::residual_fingerprint(verified.record())?;
        if fingerprint != head.fingerprint {
            return Err(FrfError::new(format!(
                "residual {} no longer matches the committed knowledge universe: its fingerprint rederives to {} but the universe committed {} — the exact disagreement the claim's absence search depended on is gone",
                head.id,
                &fingerprint[..16],
                &head.fingerprint[..16]
            )));
        }
    }

    // Every committed object, by kind: the object exists and its content
    // address rederives to the committed cid.
    for obj in &universe.objects {
        let ok = match obj.kind.as_str() {
            "receipt" => {
                // load_receipt_verified proves the canonical body hashes to
                // the id's digest component; the committed cid IS that digest.
                load_receipt_verified(store, &obj.id)
                    .map_err(|e| {
                        FrfError::new(format!(
                            "the committed knowledge universe names receipt {} but it is not verifiable evidence in this store: {e}",
                            obj.id
                        ))
                    })?;
                obj.id
                    .strip_prefix("receipt-")
                    .and_then(|rest| rest.rsplit_once('-'))
                    .map(|(_, d)| d == obj.cid)
                    .unwrap_or(false)
            }
            "run" => {
                // load_capture_verified proves the recorded fields hash to
                // the run identity; the committed cid IS its digest.
                load_capture_verified(store, &obj.id)
                    .map_err(|e| {
                        FrfError::new(format!(
                            "the committed knowledge universe names run {} but it is not verifiable evidence in this store: {e}",
                            obj.id
                        ))
                    })?;
                obj.id
                    .strip_prefix("run-")
                    .and_then(|rest| rest.rsplit_once('-'))
                    .map(|(_, d)| d == obj.cid)
                    .unwrap_or(false)
            }
            "authority" => {
                // An authority id is a LABEL; the committed cid is the
                // canonical hash of its record — the exact bytes the blocker
                // scan's lineage computation reads.
                let record = store.load_authority(&obj.id).map_err(|e| {
                    FrfError::new(format!(
                        "the committed knowledge universe names authority {} but it is not present in this store: {e}",
                        obj.id
                    ))
                })?;
                crate::semantics::record_content_identity(&record)? == obj.cid
            }
            "series" => {
                // The series id IS its content address; the loader proves it
                // rederives from the record's fields. The committed cid must
                // equal that id.
                store.load_series(&obj.id).map_err(|e| {
                    FrfError::new(format!(
                        "the committed knowledge universe names series {} but it is not verifiable evidence in this store: {e}",
                        obj.id
                    ))
                })?;
                obj.cid == obj.id
            }
            "reduction" => {
                // The reduction id IS its content address; the loader proves
                // it rederives from the record's fields.
                store.load_reduction(&obj.id).map_err(|e| {
                    FrfError::new(format!(
                        "the committed knowledge universe names reduction {} but it is not verifiable evidence in this store: {e}",
                        obj.id
                    ))
                })?;
                obj.cid == obj.id
            }
            other => {
                return Err(FrfError::new(format!(
                    "the committed knowledge universe names an unknown object kind {other:?} — only receipt/run/authority/series/reduction are universe members"
                )))
            }
        };
        if !ok {
            return Err(FrfError::new(format!(
                "object {} ({}) in the committed knowledge universe no longer matches its committed content address — a store that mutated evidence the claim names cannot re-verify it",
                obj.id, obj.kind
            )));
        }
    }
    Ok(())
}

/// Load + verify a COMPILED claim before anything may consume it — the
/// renderers' admission gate:
///
/// 1. the document is strict canonical JSON and the claim id rederives
///    (`FRF/CLAIM/v1` over the canonical document minus the id);
/// 2. every premise receipt is [`ReceiptVerified`];
/// 3. subject coherence: the premises bind the same authority and the same
///    candidate artifact, matching the claim's recorded ones;
/// 4. K rederives from the verified premises and EQUALS the recorded scope;
///    containment `Scope(K) ⊆ Scope(P₁ ∪ … ∪ Pₙ)` is re-checked literally;
/// 5. the committed knowledge universe U is reproducible WITHIN the store
///    (containment: U's objects must still exist and match — the store may
///    have grown, but must not have lost or mutated anything U names), and
///    the blocker search re-runs over the COMMITTED universe U (an
///    open/unknown residual in U intersecting K refuses the claim — a claim
///    with a blocker is not renderable);
/// 6. the policy's evidence re-verifies: capability coverage per claimed
///    axis, an affirming, subject-REBOUND witness attestation per premise,
///    an admissible independence relation per premise, and the replay
///    contract for `high-assurance`;
/// 7. the derived projections (`observable_scope`, `excluded_evidence`)
///    rederive.
///
/// THE SUBJECT BINDING of a trajectory premise (frf-claim-v12): the premise
/// names the anchored premise receipt the movement is evidence about. This
/// is the check that makes a movement premise about the SAME subject as the
/// claim — two independently valid trajectories on the same axis about
/// different authorities cannot become premises of one claim:
///
/// 1. `receipt ∈ claim.requires` — the movement anchors a premise of THIS
///    claim;
/// 2. `anchor_run == receipt.run`, and that run is a point of the
///    trajectory's series, which belongs to the anchored receipt's court;
/// 3. the axis is a CLEAN DECLARED OBSERVABLE of the anchored receipt (the
///    anchored premise observed the axis, and observed it passing);
/// 4. the trajectory's lineage REDERIVES from the anchored receipt's
///    authority / fixture-family / fixture semantics (kind and surface come
///    from the movement's own first observed residual record — the anchored
///    receipt may be the clean point where the divergence ceases);
/// 5. on `candidate_revision`, the anchored point's run executed the
///    claim's candidate artifact — the point of the trajectory that
///    corresponds to the candidate the parity claim is about (the other
///    points vary by design).
///
/// The claim compiler and the verified loader share this one function: a
/// compiled claim passes its own loader by construction.
pub fn verify_trajectory_premise_binding(
    store: &Store,
    p: &crate::model::TrajectoryPremise,
    requires: &[String],
    claim_candidate_identity: &str,
) -> Result<()> {
    // 1. The anchored receipt is a premise of this claim.
    if !requires.iter().any(|r| r == &p.receipt) {
        return Err(FrfError::new(format!(
            "trajectory premise {}.{}.{} anchors receipt {}, which is not a premise of this claim — a movement premise must bind a receipt the claim requires",
            p.lineage, p.coordinate_system, p.series, p.receipt
        )));
    }
    let anchored = load_receipt_verified(store, &p.receipt)?;
    let anchored = anchored.body();
    // 2. The anchor run IS the anchored receipt's run, and it is a point of
    //    the trajectory's series — which belongs to the anchored receipt's
    //    court (the movement was observed over the anchored premise's own
    //    experiment).
    if p.anchor_run != anchored.run {
        return Err(FrfError::new(format!(
            "trajectory premise {}.{}.{}: its anchor run {} is not the anchored receipt {}'s run ({}) — the anchor is a derived relation, never an asserted one",
            p.lineage, p.coordinate_system, p.series, p.anchor_run, p.receipt, anchored.run
        )));
    }
    let series = store.load_series(&p.series)?;
    if series.court != anchored.court.id {
        return Err(FrfError::new(format!(
            "trajectory premise {}.{}.{}: its series belongs to court {}, not the anchored receipt {}'s court {} — the movement was not observed over the anchored premise's experiment",
            p.lineage, p.coordinate_system, p.series, series.court, p.receipt, anchored.court.id
        )));
    }
    if !series.points.iter().any(|pt| pt.run == p.anchor_run) {
        return Err(FrfError::new(format!(
            "trajectory premise {}.{}.{}: its anchor run {} is not a point of the series — the anchored receipt was not observed over this movement's experiment",
            p.lineage, p.coordinate_system, p.series, p.anchor_run
        )));
    }
    // 3. The axis is a clean declared observable of the anchored receipt.
    let declared_clean = anchored
        .observables
        .iter()
        .any(|o| o.axis == p.axis && o.verdict == crate::model::ObservableVerdict::Pass)
        && !anchored.residuals.iter().any(|res| res.axis == p.axis);
    if !declared_clean {
        return Err(FrfError::new(format!(
            "trajectory premise {}.{}.{} is about axis {}, which is not a clean declared observable of its anchored receipt {} — a movement premise must be about a surface the anchored premise observed, and observed passing",
            p.lineage, p.coordinate_system, p.series, p.axis, p.receipt
        )));
    }
    // 4. The lineage rederives from the anchored receipt's subject
    //    semantics (the movement's own first observed residual record names
    //    kind/surface; the anchored receipt names authority/family/fixture).
    let doc = store.load_trajectory(&p.lineage, &p.coordinate_system, &p.series)?;
    let rederived =
        crate::semantics::trajectory_lineage_from_receipt(store, anchored, &p.axis, &doc)?;
    if rederived != p.lineage {
        return Err(FrfError::new(format!(
            "trajectory premise {}.{}.{} is NOT about the anchored receipt {}'s subject: its lineage rederives to {} from the receipt's authority/fixture-family/fixture semantics, not {} — a trajectory about a different reference or family is not a movement premise of this claim, however valid its graph",
            p.lineage,
            p.coordinate_system,
            p.series,
            p.receipt,
            &rederived[..16],
            &p.lineage[..16]
        )));
    }
    // 5. On candidate_revision the candidate varies by design — prove WHICH
    //    point of the trajectory corresponds to the candidate the parity
    //    claim is about: the anchored point's run must have executed the
    //    claim's candidate artifact.
    if p.coordinate_system == "candidate_revision" {
        let capture = load_capture_verified(store, &p.anchor_run)?;
        if capture.capture.candidate_artifact.sha256 != claim_candidate_identity {
            return Err(FrfError::new(format!(
                "trajectory premise {}.{}.{}: its anchored point {} executed candidate {}, not the claim's candidate {} — the point of the trajectory that corresponds to the claimed candidate must be the anchored one",
                p.lineage,
                p.coordinate_system,
                p.series,
                p.anchor_run,
                &capture.capture.candidate_artifact.sha256[..16],
                &claim_candidate_identity[..16]
            )));
        }
    }
    Ok(())
}

pub fn load_claim_verified(store: &Store, id: &str) -> Result<ClaimVerified> {
    let claim = store.load_claim(id)?;

    // 1.5 The transform declaration is the CLAIM transform: nothing varies
    //     — parity over the premises, committed by the content address. A
    //     claim whose declaration was relabeled is not evidence.
    let claim_transform_ok = claim.transform.kind == "claim"
        && claim.transform.source == claim.receipt
        && claim.transform.varying_dimensions.is_empty()
        && claim.transform.invariant_dimensions == ["candidate", "authority"]
        && claim.transform.observation_relation == "parity"
        && claim.transform.success_predicate == "scope-admitted";
    if !claim_transform_ok {
        return Err(FrfError::new(format!(
            "claim {id}: its transform declaration is not the claim transform (nothing varies; parity over the premises; scope-admitted) — a relabeled claim is not evidence"
        )));
    }

    // 2. Every premise is a verified receipt.
    let mut premises: Vec<ReceiptVerified> = Vec::new();
    for prem_id in &claim.requires {
        premises.push(load_receipt_verified(store, prem_id)?);
    }
    if premises.is_empty() {
        return Err(FrfError::new(format!(
            "claim {id} names no premise receipts"
        )));
    }
    let bodies: Vec<&Receipt> = premises.iter().map(|p| p.body()).collect();
    let first = bodies[0];

    // 3. Subject coherence: all premises bind the same authority and the
    //    same candidate artifact — matching the claim's recorded ones.
    for r in &bodies[1..] {
        if r.authority.name != first.authority.name
            || r.authority.version != first.authority.version
            || r.authority.identity_hash != first.authority.identity_hash
        {
            return Err(FrfError::new(format!(
                "claim {id}: the premises bind different authorities — a claim asserts parity against ONE reference"
            )));
        }
        if r.candidate.identity_hash != first.candidate.identity_hash {
            return Err(FrfError::new(format!(
                "claim {id}: the premises bind different candidate artifacts — a claim asserts parity of ONE candidate"
            )));
        }
    }
    if claim.authority != format!("{}-{}", first.authority.name, first.authority.version) {
        return Err(FrfError::new(format!(
            "claim {id}: its recorded authority does not match the premises"
        )));
    }
    if claim.candidate.identity_hash != first.candidate.identity_hash {
        return Err(FrfError::new(format!(
            "claim {id}: its recorded candidate artifact does not match the premises"
        )));
    }

    // 4. K rederives and EQUALS the recorded scope; containment re-checks.
    let k = crate::scope::claim_region(&bodies);
    if k != claim.scope {
        return Err(FrfError::new(format!(
            "claim {id}: its recorded scope does not rederive from the verified premises"
        )));
    }
    let p = crate::scope::premise_region(&bodies);
    for cell in &k.cells {
        if !p.contains(cell) {
            return Err(FrfError::new(format!(
                "claim {id}: Scope(K) ⊄ Scope(P₁ ∪ … ∪ Pₙ) — the recorded claim exceeds the premises' observed surface"
            )));
        }
    }

    // 5. The committed universe U must be reproducible WITHIN this store
    //    (containment, not equality: the store may have grown since compile
    //    time — later runs, residuals, series — but nothing U named may be
    //    lost or mutated), and the blocker search re-runs over the COMMITTED
    //    U — the claim stays a projection of the exact universe it names.
    verify_knowledge_universe(store, &claim.knowledge_snapshot)?;
    let blockers = crate::commands::claim::store_blockers(store, &k, &claim.knowledge_snapshot)?;
    if !blockers.is_empty() {
        let names: Vec<&str> = blockers.iter().map(|(b, _, _)| b.as_str()).collect();
        return Err(FrfError::new(format!(
            "claim {id} is blocked: unresolved residual(s) {} intersect its scope in the committed universe — a blocked claim is not renderable evidence",
            names.join(", ")
        )));
    }
    if !claim.blockers.is_empty() {
        return Err(FrfError::new(format!(
            "claim {id} records blockers in its IR but the blocker search over U finds none — the IR is inconsistent"
        )));
    }

    // 5b. The TRAJECTORY PREMISES (v12) re-verify: every premise's
    //     trajectory document rederives from its pinned series (id +
    //     classification + transform), the copied fields match the
    //     re-derived document, its axis is a claimed observable, the
    //     movement endpoints derive from the document's observations — never
    //     from a caller-supplied label — and the premise is BOUND to its
    //     subject (the anchored premise receipt, frf-claim-v12): an
    //     unrelated same-axis trajectory can never become a movement premise
    //     of this claim.
    for p in &claim.trajectory_premises {
        verify_trajectory_document(store, &p.lineage, &p.coordinate_system, &p.series).map_err(
            |e| {
                FrfError::new(format!(
                    "claim {id}: trajectory premise {} is not verified evidence: {e}",
                    format_args!("{}.{}.{}", p.lineage, p.coordinate_system, p.series)
                ))
            },
        )?;
        let doc = store.load_trajectory(&p.lineage, &p.coordinate_system, &p.series)?;
        if p.trajectory != doc.id
            || p.axis != doc.axis
            || p.drift != doc.derivation.drift.as_str()
            || p.slew != doc.derivation.slew.as_str()
            || p.localization != doc.derivation.localization.as_str()
            || p.bands != doc.derivation.bands
        {
            return Err(FrfError::new(format!(
                "claim {id}: trajectory premise {}.{}.{} does not match its re-derived document — a hand-edited premise is not evidence",
                p.lineage, p.coordinate_system, p.series
            )));
        }
        if !claim.observable_scope.iter().any(|a| a == &p.axis) {
            return Err(FrfError::new(format!(
                "claim {id}: trajectory premise {}.{}.{} is about axis {}, which the claim does not cover — a movement premise must be about a claimed observable",
                p.lineage, p.coordinate_system, p.series, p.axis
            )));
        }
        // THE SUBJECT BINDING (frf-claim-v12): the premise names the
        // anchored premise receipt whose run is a point of the series, the
        // axis is a clean declared observable of that receipt, and the
        // lineage rederives from the anchored receipt's subject semantics.
        verify_trajectory_premise_binding(
            store,
            p,
            &claim.requires,
            &claim.candidate.identity_hash,
        )
        .map_err(|e| {
            FrfError::new(format!(
                "claim {id}: trajectory premise {}.{}.{} is not bound to its subject: {e}",
                p.lineage, p.coordinate_system, p.series
            ))
        })?;
        // The movement endpoints re-derive from the observations.
        let mut onset: Option<String> = None;
        let mut last_observed: Option<usize> = None;
        for (i, o) in doc.observations.iter().enumerate() {
            if o.observed {
                if onset.is_none() {
                    onset = Some(o.coordinate.clone());
                }
                last_observed = Some(i);
            }
        }
        let cessation = last_observed.and_then(|last| {
            doc.observations[last + 1..]
                .iter()
                .find(|o| !o.observed)
                .map(|o| o.coordinate.clone())
        });
        if p.onset != onset || p.cessation != cessation {
            return Err(FrfError::new(format!(
                "claim {id}: trajectory premise {}.{}.{} does not derive its movement endpoints from the document's observations — onset/cessation are derived relations, never asserted ones",
                p.lineage, p.coordinate_system, p.series
            )));
        }
    }

    // 6. The admission policy's evidence re-verifies (per premise).
    if claim.policy != "baseline" {
        // Capability: every claimed axis of every premise has a verified
        // challenge record.
        for entry in &claim.capability {
            let premise = premises
                .iter()
                .find(|p| p.id() == entry.receipt)
                .ok_or_else(|| {
                    FrfError::new(format!(
                        "claim {id}: capability entry for axis {} binds premise {} which the claim does not require",
                        entry.axis, entry.receipt
                    ))
                })?;
            verify_capability_entry(store, entry, premise.id(), premise.body())?;
        }
        // Every claimed axis must have coverage.
        for axis in &claim.observable_scope {
            if !claim.capability.iter().any(|c| c.axis == *axis) {
                return Err(FrfError::new(format!(
                    "claim {id}: claimed axis {axis} has no capability coverage — the court never demonstrated it can see that surface"
                )));
            }
        }
        // The REQUIRED sensitivity mutation profile re-derives: every
        // AXIS:FAMILY pair the claim was compiled under must name a claimed
        // axis whose demonstrated profile includes that family.
        for entry in &claim.mutation_profile {
            let (axis, family) = entry.split_once(':').ok_or_else(|| {
                FrfError::new(format!(
                    "claim {id}: its required mutation profile entry {entry:?} is not AXIS:FAMILY"
                ))
            })?;
            if !claim.observable_scope.iter().any(|a| a == axis) {
                return Err(FrfError::new(format!(
                    "claim {id}: its required mutation profile names axis {axis}, which the claim does not cover"
                )));
            }
            let covered = claim
                .capability
                .iter()
                .any(|c| c.axis == axis && c.mutation_profile.iter().any(|f| f == family));
            if !covered {
                return Err(FrfError::new(format!(
                    "claim {id}: its required mutation profile demands the {family} family on axis {axis}, which no capability entry demonstrates"
                )));
            }
        }
    } else if !claim.mutation_profile.is_empty() {
        // A baseline claim names no required profile (the compiler refuses
        // it; a hand-written one is an inconsistent IR).
        return Err(FrfError::new(format!(
            "claim {id}: a {}-policy claim records a required mutation profile — the profile belongs to a sensitivity-bearing tier",
            claim.policy
        )));
    }
    if matches!(
        claim.policy.as_str(),
        "independently-witnessed" | "high-assurance"
    ) {
        if claim.witness_statements.is_empty() {
            return Err(FrfError::new(format!(
                "claim {id}: policy {} requires a witness attestation but names none",
                claim.policy
            )));
        }
        // EVERY premise must have an affirming, subject-REBOUND attestation
        // of ITSELF among the carried statements.
        let mut witnesses: Vec<WitnessStatementVerified> = Vec::new();
        for wid in &claim.witness_statements {
            witnesses.push(load_witness_statement_verified(store, wid)?);
        }
        for prem_id in &claim.requires {
            let affirmed = witnesses.iter().any(|w| {
                w.subject().kind == "receipt"
                    && w.subject().id == *prem_id
                    && w.statement().attestation.outcome == "affirm"
            });
            if !affirmed {
                return Err(FrfError::new(format!(
                    "claim {id}: no named witness affirms premise receipt {prem_id}"
                )));
            }
        }
        // At least one admissible independence relation per premise, bound
        // to an attestation of THAT premise.
        for prem_id in &claim.requires {
            let covered = claim.independence_evidence.iter().any(|iid| {
                store
                    .load_independence(iid)
                    .map(|rec| {
                        witnesses
                            .iter()
                            .any(|w| w.id() == rec.witness_statement && w.subject().id == *prem_id)
                    })
                    .unwrap_or(false)
            });
            if !covered {
                return Err(FrfError::new(format!(
                    "claim {id}: premise receipt {prem_id} has no admissible independence relation — an attestation alone is witnessed, not independently witnessed"
                )));
            }
        }
    }
    if claim.policy == "high-assurance" {
        for r in &bodies {
            if r.execution_profile != crate::model::EXECUTION_PROFILE_LINUX {
                return Err(FrfError::new(format!(
                    "claim {id}: high-assurance requires the reference execution profile for every premise"
                )));
            }
            if r.capture_bounds != crate::host::reference_capture_bounds() {
                return Err(FrfError::new(format!(
                    "claim {id}: high-assurance requires the reference capture bounds for every premise"
                )));
            }
            // Native artifacts must bind their runtime closure: for native
            // software, executable hash is not executable semantics — a
            // high-assurance premise must name what its artifacts actually
            // loaded.
            for (who, artifact) in [
                (
                    "authority",
                    (&r.authority.interpreter, &r.authority.native_runtime),
                ),
                (
                    "candidate",
                    (&r.candidate.interpreter, &r.candidate.native_runtime),
                ),
            ] {
                if artifact.0.is_none() && artifact.1.is_none() {
                    return Err(FrfError::new(format!(
                        "claim {id}: the premise {} is a NATIVE artifact whose runtime closure is not bound — high-assurance native evidence must name the dynamic loader and the resolved dependency closure",
                        who
                    )));
                }
            }
        }
        if claim.replay_profile != crate::model::EXECUTION_PROFILE_LINUX {
            return Err(FrfError::new(format!(
                "claim {id}: its replay_profile does not record the reference profile"
            )));
        }
        // The capability requirement the policy demanded must be recorded
        // exactly: the claim reasons over orthogonal capabilities, not over
        // a profile-name equality.
        let required: Vec<String> = crate::model::HIGH_ASSURANCE_CAPABILITIES
            .iter()
            .map(|c| c.to_string())
            .collect();
        if claim.required_capabilities != required {
            return Err(FrfError::new(format!(
                "claim {id}: its required_capabilities do not record the high-assurance capability set"
            )));
        }
    }

    // 7. The derived projections rederive.
    if claim.observable_scope != crate::scope::region_observables(&k) {
        return Err(FrfError::new(format!(
            "claim {id}: its observable_scope does not rederive from its scope"
        )));
    }
    let excluded = crate::scope::region_excluded_evidence(&bodies, &k);
    if claim.excluded_evidence != excluded {
        return Err(FrfError::new(format!(
            "claim {id}: its excluded_evidence does not rederive from the premises"
        )));
    }
    // The remaining IR fields are pure renderings of the verified evidence
    // and must rederive exactly: the proposition is the deterministic
    // rendering of K, the relation is the clean axes' comparators, the
    // environment label is the first premise's arch-os + digest prefix, and
    // the court + fixture family are the first premise's. A tampered
    // proposition or label is a tampered claim, not a rendering of it.
    let mut expected_proposition = format!(
        "parity(cells=[{}])",
        k.cells
            .iter()
            .map(crate::commands::claim::cell_proposition)
            .collect::<Vec<_>>()
            .join(",")
    );
    if !claim.trajectory_premises.is_empty() {
        expected_proposition.push_str(" + ");
        expected_proposition.push_str(&crate::commands::claim::movement_proposition(
            &claim.trajectory_premises,
        ));
    }
    if claim.proposition != expected_proposition {
        return Err(FrfError::new(format!(
            "claim {id}: its proposition does not rederive from its scope — the claim does not say what its evidence says"
        )));
    }
    let mut expected_relation: Vec<String> = Vec::new();
    for r in &bodies {
        for obs in &r.observables {
            if !r.residuals.iter().any(|res| res.axis == obs.axis)
                && !expected_relation.contains(&obs.comparator)
            {
                expected_relation.push(obs.comparator.clone());
            }
        }
    }
    if claim.relation != expected_relation.join(", ") {
        return Err(FrfError::new(format!(
            "claim {id}: its relation does not rederive from the premises' clean axes"
        )));
    }
    let expected_env = format!(
        "{}-{} ({})",
        first.environment.architecture,
        first.environment.os,
        &first.environment.digest[..8]
    );
    if claim.environment != expected_env {
        return Err(FrfError::new(format!(
            "claim {id}: its environment label does not rederive from the first premise"
        )));
    }
    if claim.court != first.court.id {
        return Err(FrfError::new(format!(
            "claim {id}: its court does not match the first premise"
        )));
    }
    if claim.fixture_family != first.court.admissibility_envelope.fixture_family {
        return Err(FrfError::new(format!(
            "claim {id}: its fixture family does not match the first premise"
        )));
    }

    Ok(ClaimVerified {
        id: id.to_string(),
        claim,
        premises,
    })
}

// ---------------------------------------------------------------------------
// OpenReceipt SEMANTIC conformance (document-level)
// ---------------------------------------------------------------------------

impl Receipt {
    /// OpenReceipt SEMANTIC conformance: the cross-field, cross-object
    /// invariants of `frf-receipt-v15`, checked on the document ALONE so any
    /// independent implementation can run the same algorithm (normative
    /// description in `spec/openreceipt.md`, corpus in
    /// `conformance/invalid-semantic/`). This is deliberately separate from
    /// structural conformance (JSON Schema + RFC 8785 + hash rules): the
    /// schema says what *shapes* are legal; this says what *documents* are.
    ///
    /// All violations are collected, so a human or an implementation sees
    /// every rule a document breaks, not just the first.
    pub fn validate_semantics(&self) -> Result<()> {
        let mut violations: Vec<String> = Vec::new();

        if self.schema_version != SCHEMA_RECEIPT {
            fail(
                &mut violations,
                format!(
                    "schema_version is {:?}, expected {SCHEMA_RECEIPT}",
                    self.schema_version
                ),
            );
        }

        // One fixture per court (v0).
        if self.fixtures.len() != 1 {
            fail(
                &mut violations,
                format!(
                    "exactly one fixture is required (found {})",
                    self.fixtures.len()
                ),
            );
        }

        // The resolved argv and the declared arguments must correspond: v0
        // courts resolve `{fixture}` to the snapshot path, `{output}` to the
        // declared produce path, and pass everything else verbatim, so every
        // resolved argument is either the declared argument or a declared
        // substitution.
        if let Some(f) = self.fixtures.first() {
            if f.arguments.len() != f.declared_arguments.len() {
                fail(
                    &mut violations,
                    "the resolved argv and the declared arguments must have the same length",
                );
            }
            for (i, (resolved, declared)) in f
                .arguments
                .iter()
                .zip(f.declared_arguments.iter())
                .enumerate()
            {
                let is_substitution = declared == "{fixture}" || declared == "{output}";
                if resolved != declared && !is_substitution {
                    fail(&mut violations, format!(
                        "argv[{i}] {resolved:?} is neither the declared argument nor a {{fixture}}/{{output}} substitution (declared {declared:?})"
                    ));
                }
            }
        }

        // Fail-closed envelope: a declared scope that is not executed would
        // falsify the evidence.
        let envelope = &self.court.admissibility_envelope;
        if envelope.replay_scope != "single-run" {
            fail(&mut violations, format!(
                "replay_scope {:?} is not executable in v0; a declared scope that is not executed would falsify the evidence",
                envelope.replay_scope
            ));
        }

        // Declared observable axes: valid protocol identifiers, and unique.
        let mut declared: Vec<&str> = Vec::new();
        for axis in &envelope.observables {
            if ObservableId::parse(axis).is_err() {
                fail(
                    &mut violations,
                    format!("invalid observable axis identifier {axis:?}"),
                );
            }
            if declared.contains(&axis.as_str()) {
                fail(
                    &mut violations,
                    format!("duplicate declared observable axis {axis:?}"),
                );
            } else {
                declared.push(axis);
            }
        }

        // The observables block: valid identifiers, unique, declared.
        let mut obs_axes: Vec<&str> = Vec::new();
        for obs in &self.observables {
            if ObservableId::parse(&obs.axis).is_err() {
                fail(
                    &mut violations,
                    format!("observable with invalid axis identifier {:?}", obs.axis),
                );
            }
            if !declared.contains(&obs.axis.as_str()) {
                fail(
                    &mut violations,
                    format!("observable {} is not declared in the envelope", obs.axis),
                );
            }
            if obs_axes.contains(&obs.axis.as_str()) {
                fail(
                    &mut violations,
                    format!("duplicate observable block for axis {}", obs.axis),
                );
            } else {
                obs_axes.push(&obs.axis);
            }
            // An observable's comparator binding is all-or-nothing: an
            // external verdict names BOTH the exact request and the exact
            // result record that produced it; an in-binary verdict names
            // neither.
            match (&obs.comparator_request, &obs.comparator_result) {
                (None, None) => {}
                (Some(_), Some(_)) => {
                    for (what, v) in [
                        ("comparator_request", obs.comparator_request.as_deref().unwrap_or("")),
                        ("comparator_result", obs.comparator_result.as_deref().unwrap_or("")),
                    ] {
                        if v.len() != 64 || !v.bytes().all(|b| b.is_ascii_hexdigit()) {
                            fail(
                                &mut violations,
                                format!("observable {} {what} must be a 64-hex content address", obs.axis),
                            );
                        }
                    }
                }
                _ => fail(&mut violations, format!(
                    "observable {} binds only one of comparator_request/comparator_result — an external verdict binds both, an in-binary verdict binds neither",
                    obs.axis
                )),
            }
        }

        // Comparator semantics: exactly one per observable axis, no orphans,
        // unique ids, and every specification hash REDERIVES from the
        // record's own fields (the record carries the full specification,
        // so a receipt cannot claim a specification its semantics do not
        // hash to).
        let mut sem_ids: Vec<&str> = Vec::new();
        for c in &self.comparator_semantics {
            if sem_ids.contains(&c.id.as_str()) {
                fail(
                    &mut violations,
                    format!("duplicate comparator semantic id {}", c.id),
                );
            } else {
                sem_ids.push(&c.id);
            }
            if !obs_axes.contains(&c.id.as_str()) {
                fail(
                    &mut violations,
                    format!("comparator semantic {} serves no observable", c.id),
                );
            }
            if c.relation_id.is_empty()
                || c.extractor.is_empty()
                || c.residual_classifier.is_empty()
            {
                fail(
                    &mut violations,
                    format!(
                        "comparator semantic {} must carry a relation, an extractor, and a residual classifier",
                        c.id
                    ),
                );
            }
            // The classifier NAMES a residual kind: it must be a registered
            // protocol kind (FRF/KIND/v1) — a comparator that classifies
            // into an unregistered kind is the same protocol hazard as a
            // residual carrying one.
            if !c.residual_classifier.is_empty() {
                if let Ok(classifier) = ResidualKind::parse(&c.residual_classifier) {
                    if classifier.schema().is_none() {
                        fail(
                            &mut violations,
                            format!(
                                "comparator semantic {}: residual classifier {:?} is not a registered protocol kind",
                                c.id, c.residual_classifier
                            ),
                        );
                    }
                }
            }
            match crate::semantics::comparator_spec_hash_rederives(c) {
                Ok(true) => {}
                Ok(false) => fail(
                    &mut violations,
                    format!(
                        "comparator semantic {}: the specification_hash does not rederive from its own fields",
                        c.id
                    ),
                ),
                Err(e) => fail(
                    &mut violations,
                    format!("comparator semantic {}: {e}", c.id),
                ),
            }
        }
        for obs in &self.observables {
            let n = self
                .comparator_semantics
                .iter()
                .filter(|c| c.id == obs.axis)
                .count();
            if n != 1 {
                fail(
                    &mut violations,
                    format!(
                        "observable {} must have exactly one comparator semantic (found {n})",
                        obs.axis
                    ),
                );
            }
        }

        // Normalizer semantics: ids must match the envelope's application
        // order EXACTLY — the order is semantic (a normalizer changes the
        // comparison surface; applying the same two normalizers in the
        // opposite order asks a different question), ids are unique, and
        // every specification hash REDERIVES from the record's own fields.
        let envelope_norm: Vec<&str> = envelope.normalizers.iter().map(String::as_str).collect();
        let rec_norm: Vec<&str> = self
            .normalizer_semantics
            .iter()
            .map(|n| n.id.as_str())
            .collect();
        if rec_norm != envelope_norm {
            fail(
                &mut violations,
                "normalizer_semantics ids must match the envelope's application order exactly",
            );
        }
        let mut norm_ids: Vec<&str> = Vec::new();
        for n in &self.normalizer_semantics {
            if norm_ids.contains(&n.id.as_str()) {
                fail(
                    &mut violations,
                    format!("duplicate normalizer semantic id {}", n.id),
                );
            } else {
                norm_ids.push(&n.id);
            }
            if !matches!(n.applies_to.as_str(), "stdout" | "stderr" | "both") {
                fail(
                    &mut violations,
                    format!(
                        "normalizer semantic {} has invalid applies_to {:?}",
                        n.id, n.applies_to
                    ),
                );
            }
            if n.relation_id.is_empty() {
                fail(
                    &mut violations,
                    format!("normalizer semantic {} must carry a relation", n.id),
                );
            }
            match crate::semantics::normalizer_spec_hash_rederives(n) {
                Ok(true) => {}
                Ok(false) => fail(
                    &mut violations,
                    format!(
                        "normalizer semantic {}: the specification_hash does not rederive from its own fields",
                        n.id
                    ),
                ),
                Err(e) => fail(
                    &mut violations,
                    format!("normalizer semantic {}: {e}", n.id),
                ),
            }
        }

        // Capture-adapter semantics: ids are declared observable axes served
        // by an external capture, unique, and every specification hash
        // REDERIVES from the record's own fields (an adapter's extraction
        // scheme is part of the question, so a receipt cannot claim a scheme
        // its own fields do not hash to).
        let mut adapter_ids: Vec<&str> = Vec::new();
        for a in &self.adapter_semantics {
            if adapter_ids.contains(&a.id.as_str()) {
                fail(
                    &mut violations,
                    format!("duplicate capture-adapter semantic id {}", a.id),
                );
            } else {
                adapter_ids.push(&a.id);
            }
            if !declared.contains(&a.id.as_str()) {
                fail(
                    &mut violations,
                    format!(
                        "capture-adapter semantic {} serves no declared observable",
                        a.id
                    ),
                );
            }
            if a.relation_id.is_empty() {
                fail(
                    &mut violations,
                    format!("capture-adapter semantic {} must carry a relation", a.id),
                );
            }
            match crate::semantics::capture_adapter_spec_hash_rederives(a) {
                Ok(true) => {}
                Ok(false) => fail(
                    &mut violations,
                    format!(
                        "capture-adapter semantic {}: the specification_hash does not rederive from its own fields",
                        a.id
                    ),
                ),
                Err(e) => fail(
                    &mut violations,
                    format!("capture-adapter semantic {}: {e}", a.id),
                ),
            }
        }

        // Provenance: every comparator semantic has a recorded implementation.
        if self.provenance.comparator_implementations.len() != self.comparator_semantics.len() {
            fail(
                &mut violations,
                "comparator_implementations must mirror comparator_semantics one-to-one",
            );
        }
        for c in &self.comparator_semantics {
            if !self
                .provenance
                .comparator_implementations
                .iter()
                .any(|i| i.id == c.id)
            {
                fail(
                    &mut violations,
                    format!(
                        "comparator semantic {} has no implementation provenance",
                        c.id
                    ),
                );
            }
        }

        // Residuals: unique ids, declared + valid axes, kind/classifier
        // consistency, disposition cross-field rules, derived grammar_state,
        // v0 sign fields, and the reproducer binding.
        let family = &envelope.fixture_family;
        let mut residual_ids: Vec<&str> = Vec::new();
        for r in &self.residuals {
            if residual_ids.contains(&r.id.as_str()) {
                fail(&mut violations, format!("duplicate residual id {}", r.id));
            } else {
                residual_ids.push(&r.id);
            }
            if ObservableId::parse(&r.axis).is_err() {
                fail(
                    &mut violations,
                    format!("residual {} has invalid axis identifier {:?}", r.id, r.axis),
                );
                continue;
            }
            if !declared.contains(&r.axis.as_str()) {
                fail(
                    &mut violations,
                    format!(
                        "residual {} axis {} is not a declared observable",
                        r.id, r.axis
                    ),
                );
            }
            if ResidualKind::parse(r.kind.as_str()).is_err() {
                fail(
                    &mut violations,
                    format!("residual {} has invalid kind {:?}", r.id, r.kind.as_str()),
                );
            }
            // The kind must be a REGISTERED protocol kind (FRF/KIND/v1): an
            // unregistered kind is a protocol this engine does not know, and
            // evidence classified into it cannot be interpreted — fail
            // closed. The registered vocabulary is pinned in the conformance
            // corpus (`conformance/kinds/`).
            if let Ok(kind) = ResidualKind::parse(r.kind.as_str()) {
                if kind.schema().is_none() {
                    fail(
                        &mut violations,
                        format!(
                            "residual {} kind {:?} is not a registered protocol kind",
                            r.id,
                            r.kind.as_str()
                        ),
                    );
                }
            }
            // The residual kind is the axis's comparator's residual
            // classifier — the classifier is part of the question, so a
            // residual whose kind disagrees with its comparator is
            // inconsistent evidence.
            let classifier = self
                .comparator_semantics
                .iter()
                .find(|c| c.id == r.axis)
                .map(|c| c.residual_classifier.as_str());
            if classifier != Some(r.kind.as_str()) {
                fail(
                    &mut violations,
                    format!(
                        "residual {} kind {:?} is inconsistent with the {} axis's residual classifier {:?}",
                        r.id,
                        r.kind.as_str(),
                        r.axis,
                        classifier.unwrap_or("<none>")
                    ),
                );
            }
            match r.disposition.as_str() {
                "open" => {
                    if r.reason.is_some() {
                        fail(
                            &mut violations,
                            format!("open residual {} carries a reason", r.id),
                        );
                    }
                    if r.resolution_run_id.is_some() {
                        fail(
                            &mut violations,
                            format!("open residual {} carries a resolution_run_id", r.id),
                        );
                    }
                    if r.closure_predicate.is_some() {
                        fail(
                            &mut violations,
                            format!("open residual {} carries a closure_predicate", r.id),
                        );
                    }
                    if r.observation_run_id.is_some() {
                        fail(
                            &mut violations,
                            format!("open residual {} carries an observation_run_id", r.id),
                        );
                    }
                    if r.trajectory_id.is_some()
                        || r.consecutive_passes.is_some()
                        || r.stabilization_bound.is_some()
                    {
                        fail(
                            &mut violations,
                            format!(
                                "open residual {} carries trajectory evidence (trajectory_id/consecutive_passes/stabilization_bound)",
                                r.id
                            ),
                        );
                    }
                    if r.disposition_event_id.is_some() {
                        fail(
                            &mut violations,
                            format!(
                                "open residual {} carries a disposition_event_id (open is the projection of no events)",
                                r.id
                            ),
                        );
                    }
                }
                "fixed" => {
                    if r.reason.is_none() {
                        fail(
                            &mut violations,
                            format!("fixed residual {} without a reason", r.id),
                        );
                    }
                    if r.resolution_run_id.is_none() {
                        fail(&mut violations, format!(
                            "fixed residual {} without a resolution_run_id — a disposition must not substitute for new evidence",
                            r.id
                        ));
                    }
                    if r.closure_predicate.as_deref() != Some(CLOSURE_PREDICATE_FIX_COURT) {
                        fail(
                            &mut violations,
                            format!(
                                "fixed residual {} must carry the fix-court closure predicate",
                                r.id
                            ),
                        );
                    }
                    if r.observation_run_id.is_some()
                        || r.trajectory_id.is_some()
                        || r.consecutive_passes.is_some()
                        || r.stabilization_bound.is_some()
                    {
                        fail(
                            &mut violations,
                            format!(
                                "fixed residual {} carries non-fix evidence edges (observation_run_id/trajectory_id/consecutive_passes/stabilization_bound)",
                                r.id
                            ),
                        );
                    }
                    if r.disposition_event_id.is_none() {
                        fail(
                            &mut violations,
                            format!(
                                "fixed residual {} without a disposition_event_id — a receipt must point at the exact event that supplied the disposition",
                                r.id
                            ),
                        );
                    }
                }
                "nonreproduced" => {
                    if r.reason.is_none() {
                        fail(
                            &mut violations,
                            format!("nonreproduced residual {} without a reason", r.id),
                        );
                    }
                    if r.observation_run_id.is_none() {
                        fail(
                            &mut violations,
                            format!(
                                "nonreproduced residual {} without an observation_run_id — a disposition must not substitute for new evidence",
                                r.id
                            ),
                        );
                    }
                    if r.resolution_run_id.is_some() || r.closure_predicate.is_some() {
                        fail(
                            &mut violations,
                            format!(
                                "nonreproduced residual {} carries resolution_run_id/closure_predicate — only fixed may",
                                r.id
                            ),
                        );
                    }
                    if r.trajectory_id.is_some()
                        || r.consecutive_passes.is_some()
                        || r.stabilization_bound.is_some()
                    {
                        fail(
                            &mut violations,
                            format!(
                                "nonreproduced residual {} carries trajectory evidence — only stabilized may",
                                r.id
                            ),
                        );
                    }
                    if r.disposition_event_id.is_none() {
                        fail(
                            &mut violations,
                            format!(
                                "nonreproduced residual {} without a disposition_event_id — a receipt must point at the exact event that supplied the disposition",
                                r.id
                            ),
                        );
                    }
                }
                "stabilized" => {
                    if r.reason.is_none() {
                        fail(
                            &mut violations,
                            format!("stabilized residual {} without a reason", r.id),
                        );
                    }
                    if r.trajectory_id.is_none()
                        || r.consecutive_passes.is_none()
                        || r.stabilization_bound.is_none()
                    {
                        fail(
                            &mut violations,
                            format!(
                                "stabilized residual {} requires trajectory_id + consecutive_passes + stabilization_bound — a disposition must not substitute for new evidence",
                                r.id
                            ),
                        );
                    }
                    if r.resolution_run_id.is_some()
                        || r.closure_predicate.is_some()
                        || r.observation_run_id.is_some()
                    {
                        fail(
                            &mut violations,
                            format!(
                                "stabilized residual {} carries resolution_run_id/closure_predicate/observation_run_id — only fixed/nonreproduced may",
                                r.id
                            ),
                        );
                    }
                    if r.disposition_event_id.is_none() {
                        fail(
                            &mut violations,
                            format!(
                                "stabilized residual {} without a disposition_event_id — a receipt must point at the exact event that supplied the disposition",
                                r.id
                            ),
                        );
                    }
                }
                other => {
                    if ClosureKind::parse(other).is_none() {
                        fail(
                            &mut violations,
                            format!("residual {} has unknown disposition {other:?}", r.id),
                        );
                    }
                    if r.reason.is_none() {
                        fail(
                            &mut violations,
                            format!("{other} residual {} requires a reason", r.id),
                        );
                    }
                    if r.resolution_run_id.is_some() {
                        fail(
                            &mut violations,
                            format!("{other} residual {} carries a resolution_run_id", r.id),
                        );
                    }
                    if r.closure_predicate.is_some() {
                        fail(
                            &mut violations,
                            format!("{other} residual {} carries a closure_predicate", r.id),
                        );
                    }
                    if r.observation_run_id.is_some() {
                        fail(
                            &mut violations,
                            format!("{other} residual {} carries an observation_run_id", r.id),
                        );
                    }
                    if r.trajectory_id.is_some()
                        || r.consecutive_passes.is_some()
                        || r.stabilization_bound.is_some()
                    {
                        fail(
                            &mut violations,
                            format!(
                                "{other} residual {} carries trajectory evidence — only stabilized may",
                                r.id
                            ),
                        );
                    }
                    if r.disposition_event_id.is_none() {
                        fail(
                            &mut violations,
                            format!(
                                "{other} residual {} without a disposition_event_id — a receipt must point at the exact event that supplied the disposition",
                                r.id
                            ),
                        );
                    }
                }
            }
            if let Some(d) = disposition_of(r) {
                let expected = kappa::grammar_state(&d);
                if r.grammar_state != expected {
                    fail(
                        &mut violations,
                        format!(
                            "grammar_state of {} is {:?}, expected {:?}",
                            r.id, r.grammar_state, expected
                        ),
                    );
                }
            }
            // The sign: the trajectory evidence per coordinate system. A
            // single-run receipt honestly carries NO entries — one run
            // cannot observe drift or slew. Every entry names a valid
            // coordinate system with a pinned series and a well-formed
            // drift/slew, and a coordinate system appears at most once.
            let mut seen_coordinate_systems: Vec<&str> = Vec::new();
            for entry in &r.sign.trajectory_evidence {
                if !matches!(
                    entry.coordinate_system.as_str(),
                    "repeat_index"
                        | "candidate_revision"
                        | "authority_version"
                        | "environment"
                        | "time"
                ) {
                    fail(
                        &mut violations,
                        format!(
                            "residual {} names unknown trajectory coordinate system {:?}",
                            r.id, entry.coordinate_system
                        ),
                    );
                }
                if seen_coordinate_systems.contains(&entry.coordinate_system.as_str()) {
                    fail(
                        &mut violations,
                        format!(
                            "residual {} names coordinate system {} twice in its trajectory evidence",
                            r.id, entry.coordinate_system
                        ),
                    );
                }
                seen_coordinate_systems.push(&entry.coordinate_system);
                if entry.series.is_empty() {
                    fail(
                        &mut violations,
                        format!(
                            "residual {} has trajectory evidence without a pinned series",
                            r.id
                        ),
                    );
                }
                if TrajectoryDrift::parse(&entry.drift).is_none() {
                    fail(
                        &mut violations,
                        format!(
                            "residual {} has invalid drift {:?} in its trajectory evidence",
                            r.id, entry.drift
                        ),
                    );
                }
                if TrajectorySlew::parse(&entry.slew).is_none() {
                    fail(
                        &mut violations,
                        format!(
                            "residual {} has invalid slew {:?} in its trajectory evidence",
                            r.id, entry.slew
                        ),
                    );
                }
            }
            if r.reproducer != self.run {
                fail(
                    &mut violations,
                    format!(
                        "residual {} reproducer must be the receipt's run ({:?}, got {:?})",
                        r.id, self.run, r.reproducer
                    ),
                );
            }
        }

        // Verdicts: a residual verdict requires residual evidence on the axis;
        // a pass verdict excludes it.
        for obs in &self.observables {
            let has = self.residuals.iter().any(|r| r.axis == obs.axis);
            match obs.verdict {
                ObservableVerdict::Pass => {
                    if has {
                        fail(
                            &mut violations,
                            format!(
                                "pass verdict on {} while a residual exists on the axis",
                                obs.axis
                            ),
                        );
                    }
                }
                ObservableVerdict::Residual => {
                    if !has {
                        fail(
                            &mut violations,
                            format!(
                                "residual verdict on {} without any residual on the axis",
                                obs.axis
                            ),
                        );
                    }
                }
            }
        }

        // The environment digest rederives from the environment fields — the
        // host strata AND the declared execution environment map (a declared
        // variable is content-addressed input).
        let env_expected = host::environment_digest(
            &self.environment.os,
            &self.environment.architecture,
            &self.environment.kernel_release,
            &self.environment.locale,
            &self.environment.timezone,
            &self.environment.umask,
            &self.environment.environment,
        );
        if env_expected != self.environment.digest {
            fail(
                &mut violations,
                "the environment digest does not rederive from the environment fields (os/architecture/kernel_release/locale/timezone/umask + the declared environment)",
            );
        }

        // The execution profile is a valid protocol identifier, and the
        // capture bounds are positive integers within the protocol's maxima
        // (an observation is read against the harness contract it was made
        // under; the contract itself must be bounded and well-formed).
        if ObservableId::parse(&self.execution_profile).is_err() {
            fail(
                &mut violations,
                format!(
                    "invalid execution_profile identifier {:?}",
                    self.execution_profile
                ),
            );
        }
        if let Err(e) = crate::model::validate_capture_bounds(&self.capture_bounds) {
            fail(&mut violations, e.0);
        }

        // The DECLARED execution-context closure (when carried) is
        // self-authenticating at the document level: the schema version, the
        // artifact roles, the strictly-sorted order, and the content address
        // rederiving from the document's own artifacts. A closure that
        // cannot rederive its own identity is not evidence.
        if let Some(closure) = &self.execution_context {
            if closure.schema_version != SCHEMA_EXECUTION_CONTEXT {
                fail(
                    &mut violations,
                    format!(
                        "the execution-context closure carries schema_version {:?}, expected {SCHEMA_EXECUTION_CONTEXT}",
                        closure.schema_version
                    ),
                );
            }
            let mut prev: Option<&str> = None;
            for a in &closure.artifacts {
                if !matches!(
                    a.role.as_str(),
                    "child-executable" | "runtime-library" | "data"
                ) {
                    fail(
                        &mut violations,
                        format!(
                            "execution-context artifact {} declares role {:?}; the protocol admits child-executable, runtime-library, or data",
                            a.path, a.role
                        ),
                    );
                }
                if let Some(p) = prev {
                    if p >= a.path.as_str() {
                        fail(
                            &mut violations,
                            format!(
                                "the execution-context artifacts are not strictly sorted by path ({} after {p})",
                                a.path
                            ),
                        );
                    }
                }
                prev = Some(&a.path);
            }
            match crate::semantics::execution_context_identity(closure) {
                Ok(h) if h != closure.cid => fail(
                    &mut violations,
                    "the execution-context closure cid does not rederive from its own artifacts",
                ),
                Err(e) => fail(
                    &mut violations,
                    format!("the execution-context closure cannot be rederived: {e}"),
                ),
                _ => {}
            }
        }

        // The court semantic identity rederives from the document.
        match crate::semantics::court_semantic_identity_from_receipt(self) {
            Ok(h) if h != self.court.semantic_identity => {
                fail(
                    &mut violations,
                    "the court semantic identity does not rederive from the document",
                );
            }
            Err(e) => fail(
                &mut violations,
                format!("the court semantic identity cannot be rederived: {e}"),
            ),
            _ => {}
        }

        // The replay block is a real court-run invocation of THIS run.
        if self.replay.program != "frf" {
            fail(
                &mut violations,
                format!(
                    "replay.program must be \"frf\", got {:?}",
                    self.replay.program
                ),
            );
        }
        if self.replay.expected_run_identity != self.run {
            fail(
                &mut violations,
                "replay.expected_run_identity must equal the receipt's run",
            );
        }
        if self.replay.argv.len() < 5
            || self.replay.argv[0] != "--root"
            || self.replay.argv[2] != "court"
            || self.replay.argv[3] != "run"
        {
            fail(
                &mut violations,
                "replay.argv must be a court-run invocation: [--root, ROOT, court, run, MANIFEST]",
            );
        }

        // Endoduction tokens: same residual set, same order, each rederivable
        // from kind/axis/disposition via the κ table.
        if self.endoduction.tokens.len() != self.residuals.len() {
            fail(
                &mut violations,
                "endoduction tokens must mirror residuals one-to-one",
            );
        }
        for (r, t) in self.residuals.iter().zip(&self.endoduction.tokens) {
            if t.residual_id != r.id {
                fail(
                    &mut violations,
                    format!(
                        "token bound to {} but the residual is {}",
                        t.residual_id, r.id
                    ),
                );
                continue;
            }
            let axis = match ObservableId::parse(&r.axis) {
                Ok(a) => a,
                Err(_) => continue,
            };
            let shape = kappa::token_shape(&axis);
            let expected_token = format!(
                "{}/{}/{}/{}",
                r.kind.as_str(),
                shape.surface,
                shape.magnitude,
                r.disposition
            );
            if t.token != expected_token {
                fail(
                    &mut violations,
                    format!(
                        "token of {} is {:?}, expected {:?}",
                        r.id, t.token, expected_token
                    ),
                );
            }
            if t.next_court != shape.next_court {
                fail(
                    &mut violations,
                    format!(
                        "next_court of {} is {:?}, expected {:?}",
                        r.id, t.next_court, shape.next_court
                    ),
                );
            }
            let expected_blocks = kappa::blocks_claims(&axis, family);
            if t.blocks_claims != expected_blocks {
                fail(
                    &mut violations,
                    format!("blocks_claims of {} does not rederive", r.id),
                );
            }
        }

        // Interpreter chains are internally consistent: an env resolver must
        // BE the kernel interpreter it resolved through; without a resolver
        // the kernel must BE the downstream interpreter.
        for (who, interp) in [
            ("authority", &self.authority.interpreter),
            ("candidate", &self.candidate.interpreter),
        ] {
            if let Some(i) = interp {
                match &i.resolver {
                    Some(r) => {
                        if r.kind != "env" {
                            fail(
                                &mut violations,
                                format!(
                                    "{who} interpreter resolver kind must be \"env\", got {:?}",
                                    r.kind
                                ),
                            );
                        }
                        if r.path != i.kernel_interpreter.path {
                            fail(&mut violations, format!(
                                "{who} interpreter resolver path must be the kernel interpreter path"
                            ));
                        }
                    }
                    None => {
                        if i.kernel_interpreter != i.downstream_interpreter {
                            fail(&mut violations, format!(
                                "{who} interpreter: without a resolver the kernel must BE the downstream interpreter"
                            ));
                        }
                    }
                }
            }
        }

        // Claims: v0 receipts never carry positive claims — the claim
        // compiler writes claims/ files from a verified receipt.
        if !self.claims.positive.is_empty() {
            fail(
                &mut violations,
                "v0 receipts carry no positive claims; the claim compiler writes claims/",
            );
        }

        if violations.is_empty() {
            Ok(())
        } else {
            Err(FrfError::new(format!(
                "OpenReceipt semantic conformance: {}",
                violations.join("; ")
            )))
        }
    }
}

