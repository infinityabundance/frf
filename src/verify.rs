/// A receipt whose identity AND derivation have been verified against the
/// evidence tree. Private fields: the only constructor is
/// [`load_receipt_verified`], so a `ReceiptVerified` cannot be fabricated —
/// `claim compile` accepts only this type.
pub struct ReceiptVerified {
    id: String,
    body: Receipt,
    /// The declared-detached content addresses the receipt's evidence
    /// closure hit: the graph verified, the object closure is
    /// incomplete-by-policy.
    detached: Vec<crate::model::DetachedObjectRef>,
}

impl ReceiptVerified {
    pub fn id(&self) -> &str {
        &self.id
    }

    pub fn body(&self) -> &Receipt {
        &self.body
    }

    /// The declared-detached payloads in this receipt's evidence closure
    /// (empty when the closure is complete).
    pub fn detached(&self) -> &[crate::model::DetachedObjectRef] {
        &self.detached
    }
}

/// Push one semantic-conformance violation (accepts literals and formatted
/// Strings alike).
fn fail(violations: &mut Vec<String>, msg: impl Into<String>) {
    violations.push(msg.into());
}

/// The sign a receipt entry MUST carry for a residual record: the
/// trajectory evidence PER COORDINATE SYSTEM. A single-run court (no series
/// membership at emit time) honestly records NO entries — one run cannot
/// observe drift or slew. A run that belongs to an [`ExecutionSeries`]
/// derives one entry per coordinate system, each PINNING the exact series
/// snapshot the drift/slew were derived from (the NEWEST snapshot containing
/// the run — the immutable head of the chain at the time; a later experiment
/// referencing the same content-addressed run can never change what an
/// emitted receipt means, because the receipt points at a fixed node).
/// One function, shared by receipt emission and the verification suite.
pub fn sign_for(
    store: &Store,
    _capture: &CaptureManifest,
    record: &ResidualRecord,
) -> Result<ResidualSign> {
    let lineage = crate::semantics::residual_lineage_of_record(store, record)?;
    let series = store.series_containing_run(&record.run)?;
    // Candidates per coordinate system: the series snapshots that contain the
    // run AND have a trajectory for this lineage.
    let mut candidates: std::collections::BTreeMap<String, Vec<String>> = Default::default();
    for s in &series {
        let path = store.trajectory_path(&lineage, &s.coordinate_system, &s.id)?;
        if !path.is_file() {
            continue;
        }
        candidates
            .entry(s.coordinate_system.clone())
            .or_default()
            .push(s.id.clone());
    }
    let mut evidence: Vec<TrajectoryEvidence> = Vec::new();
    for (coordinate_system, mut ids) in candidates {
        // The NEWEST snapshot among the candidates: the one that is a
        // descendant of every other candidate (chain position, not length or
        // directory order). Incomparable candidates (a branch) fall back to
        // id order — deterministic, and the verifier replays the PINNED node.
        ids.sort();
        let newest = ids
            .iter()
            .find(|a| {
                ids.iter()
                    .all(|b| store.series_is_descendant_of(a, b).unwrap_or(false))
            })
            .cloned()
            .unwrap_or_else(|| ids[0].clone());
        let t = store.load_trajectory(&lineage, &coordinate_system, &newest)?;
        evidence.push(TrajectoryEvidence {
            coordinate_system: coordinate_system.clone(),
            series: newest,
            drift: t.derivation.drift.as_str().to_string(),
            slew: t.derivation.slew.as_str().to_string(),
        });
    }
    Ok(ResidualSign {
        trajectory_evidence: evidence,
    })
}

/// Verify a trajectory DOCUMENT as evidence. The trajectory is a DERIVED
/// protocol object (frf-trajectory-v6): (1) it matches its document address
/// (the derivation key `subject.coordinate_system.series`); (2) its content
/// address rederives (`FRF/TRAJECTORY/v1` over the canonical document minus
/// the id — the transform declaration included, so a relabeled trajectory is
/// a different id); and (3) it is the EXACT derivation from its pinned
/// series — the observations, the deterministic classification, and the
/// transform declaration are re-derived from the verified series and the
/// documents compared byte-for-byte. A trajectory that fails any of these is
/// not evidence.
pub fn verify_trajectory_document(
    store: &Store,
    subject: &str,
    coordinate_system: &str,
    series: &str,
) -> Result<()> {
    let t = store.load_trajectory(subject, coordinate_system, series)?;
    if t.subject != subject || t.coordinate_system != coordinate_system || t.series != series {
        return Err(FrfError::new(format!(
            "trajectory {}: the record does not match its document address",
            t.id
        )));
    }
    let rederived = crate::semantics::trajectory_identity(&t)?;
    if t.id != rederived {
        return Err(FrfError::new(format!(
            "trajectory {} (subject {}): the record does not rederive its content address — a hand-edited or relabeled trajectory is not evidence",
            &t.id[..16.min(t.id.len())],
            &subject[..16.min(subject.len())]
        )));
    }
    let series_rec = store.load_series(series)?;
    let rederived_rec = crate::store::derive_lineage_trajectory(store, &series_rec, subject)?;
    let stored_canon = crate::canon::canonical(&t)?;
    let derived_canon = crate::canon::canonical(&rederived_rec)?;
    if stored_canon != derived_canon {
        return Err(FrfError::new(format!(
            "trajectory {} does not re-derive from its series — the stored document is not the exact derivation of its pinned evidence",
            &t.id[..16.min(t.id.len())]
        )));
    }
    Ok(())
}

/// Verify a receipt entry's sign against the evidence it PINNED. Every entry
/// names the exact ExecutionSeries snapshot the drift/slew were derived
/// from; the verifier replays THAT series (it must exist, contain the run,
/// and its trajectory for the residual's lineage must yield the recorded
/// drift/slew). An empty `trajectory_evidence` is a single-run snapshot: the
/// absence of a series at emit time is not reconstructible, so it is
/// accepted as-is — a later experiment referencing the same content-addressed
/// run does not rewrite an emitted receipt.
pub fn verify_sign(store: &Store, record: &ResidualRecord, sign: &ResidualSign) -> Result<()> {
    let lineage = crate::semantics::residual_lineage_of_record(store, record)?;
    let mut seen_coordinate_systems: Vec<&str> = Vec::new();
    for entry in &sign.trajectory_evidence {
        if !matches!(
            entry.coordinate_system.as_str(),
            "repeat_index" | "candidate_revision" | "authority_version" | "environment" | "time"
        ) {
            return Err(FrfError::new(format!(
                "residual {}: trajectory evidence names unknown coordinate system {:?}",
                record.id, entry.coordinate_system
            )));
        }
        if seen_coordinate_systems.contains(&entry.coordinate_system.as_str()) {
            return Err(FrfError::new(format!(
                "residual {}: trajectory evidence repeats coordinate system {}",
                record.id, entry.coordinate_system
            )));
        }
        seen_coordinate_systems.push(&entry.coordinate_system);
        let series = store.load_series(&entry.series).map_err(|e| {
            FrfError::new(format!(
                "residual {}: the pinned series {} does not exist: {e}",
                record.id, entry.series
            ))
        })?;
        if series.coordinate_system != entry.coordinate_system {
            return Err(FrfError::new(format!(
                "residual {}: the pinned series {} is a {} experiment, not {}",
                record.id, entry.series, series.coordinate_system, entry.coordinate_system
            )));
        }
        if !series.points.iter().any(|p| p.run == record.run) {
            return Err(FrfError::new(format!(
                "residual {}: the pinned series {} does not contain run {}",
                record.id, entry.series, record.run
            )));
        }
        let t = store.load_trajectory(&lineage, &series.coordinate_system, &entry.series)?;
        verify_trajectory_document(store, &lineage, &series.coordinate_system, &entry.series)?;
        if entry.drift != t.derivation.drift.as_str() || entry.slew != t.derivation.slew.as_str() {
            return Err(FrfError::new(format!(
                "residual {}: drift/slew do not match the pinned series' trajectory",
                record.id
            )));
        }
    }
    Ok(())
}

/// The disposition a receipt entry claims, rebuilt from its fields after the
/// cross-field rules have validated them.
fn disposition_of(res: &ReceiptResidual) -> Option<Disposition> {
    match res.disposition.as_str() {
        "open" => Some(Disposition::Open),
        "fixed" => Some(Disposition::Fixed {
            reason: res.reason.clone()?,
            resolution_run_id: res.resolution_run_id.clone()?,
            closure_predicate: res.closure_predicate.clone()?,
        }),
        "nonreproduced" => Some(Disposition::Nonreproduced {
            reason: res.reason.clone()?,
            observation_run_id: res.observation_run_id.clone()?,
        }),
        "stabilized" => Some(Disposition::Stabilized {
            reason: res.reason.clone()?,
            trajectory_id: res.trajectory_id.clone()?,
            consecutive_passes: res.consecutive_passes.clone()?,
            stabilization_bound: res.stabilization_bound.clone()?,
        }),
        other => Some(Disposition::Closed {
            kind: ClosureKind::parse(other)?,
            reason: res.reason.clone()?,
        }),
    }
}

/// Verify a native runtime closure: its schema, its content address
/// (`FRF/RUNTIME-CLOSURE/v1` over the canonical document minus the cid — a
/// hand-edited or forged closure is refused), and every component's hash
/// shape. The resolved paths and hashes are evidence recorded at observation
/// time (machine-specific, like interpreter hashes); the CID rederives in
/// any implementation.
pub fn verify_runtime_closure(closure: &crate::model::NativeRuntimeClosure) -> Result<()> {
    if closure.schema_version != crate::model::SCHEMA_RUNTIME_CLOSURE {
        return Err(FrfError::new(format!(
            "unsupported runtime closure schema {:?} (this implementation speaks {})",
            closure.schema_version,
            crate::model::SCHEMA_RUNTIME_CLOSURE
        )));
    }
    let rederived = crate::semantics::runtime_closure_identity(closure)?;
    if rederived != closure.cid {
        return Err(FrfError::new(format!(
            "the native runtime closure is not content-addressed: its fields hash to {} but its cid claims {}; refusing to consume a hand-edited or forged closure",
            &rederived[..16],
            &closure.cid[..16]
        )));
    }
    for (what, component) in std::iter::once(("interp", &closure.interp))
        .chain(closure.components.iter().map(|c| ("component", c)))
    {
        if component.sha256.len() != 64 || !component.sha256.bytes().all(|b| b.is_ascii_hexdigit())
        {
            return Err(FrfError::new(format!(
                "the runtime closure {what} {} carries a malformed hash {:?}",
                component.path,
                &component.sha256[..component.sha256.len().min(16)]
            )));
        }
    }
    Ok(())
}

/// Verify a receipt before anything may consume it:
///
/// 1. content addressing: `id == receipt-{run}-{SHA-256(canonical body)}`;
/// 2. document-level semantic conformance ([`Receipt::validate_semantics`]);
/// 3. derivation from the verified capture: same court, artifacts,
///    environment, comparator semantics + provenance, observables, and
///    EXACTLY the run's residuals;
/// 4. per-residual derivation: the record file, the fingerprint, the κ token,
///    and dispositions evidenced by the append-only event history;
/// 5. `fixed` closures re-verified as evidence: the resolution run reran the
///    same question under a compatible envelope and the axis now closes.
pub fn load_receipt_verified(store: &Store, id: &str) -> Result<ReceiptVerified> {
    let path = store.receipt_path(id)?;
    let text = read_bytes(&path, "receipt")?;

    // 0. The protocol representation is CANONICAL JSON: the file bytes MUST
    //    be their own JCS (RFC 8785). The independent verifiers (xtask, Go)
    //    enforce exactly this — a receipt reformatted with whitespace is a
    //    DIFFERENT representation and is refused by them, so the reference
    //    engine must refuse it too, or the triangle disagrees on identical
    //    semantics. A non-canonical receipt is refused BEFORE anything may
    //    consume it.
    crate::canon::require_canonical_bytes(&text, "receipt")?;

    // 1. Content addressing begins with the DOCUMENT, never the typed
    //    projection. Strict parse refuses duplicate property names (RFC 8785
    //    §2 I-JSON — serde_json::Value would silently collapse them), then
    //    the canonical bytes are computed from the raw value, so an unknown
    //    property either survives into the digest or the receipt is refused
    //    — it can never be deserialized away before the identity is checked.
    let value = crate::canon::parse_strict(&text)?;
    let canonical = crate::canon::encode(&value)?;
    let actual = host::sha256_bytes(canonical.as_bytes());

    let rest = id
        .strip_prefix("receipt-")
        .ok_or_else(|| FrfError::new(format!("{id} is not a receipt id")))?;
    let (run, digest) = rest
        .rsplit_once('-')
        .ok_or_else(|| FrfError::new(format!("receipt id {id} must end in the digest")))?;
    if actual != digest {
        return Err(FrfError::new(format!(
            "receipt {id} is not content-addressed: its canonical body hashes to {} but its id claims {digest}; refusing to consume hand-edited or forged evidence",
            &actual[..16]
        )));
    }

    // 2. Strict structural deserialization: every OpenReceipt type carries
    //    deny_unknown_fields, so a document cannot shed bytes the content
    //    address covered (an unknown property is refused, not dropped). The
    //    schema version and the closed enums are enforced here too.
    let body: Receipt = serde_json::from_value(value)
        .map_err(|e| FrfError::new(format!("cannot deserialize {}: {e}", path.display())))?;
    if body.run != run {
        return Err(FrfError::new(format!(
            "receipt {id}: the run field inside the body is {body:?} — the name is a claim",
            body = body.run
        )));
    }

    // 3. Document-level semantic conformance.
    body.validate_semantics()
        .map_err(|e| FrfError::new(format!("receipt {id}: {e}")))?;

    // 4. The receipt derives from the verified capture of its own run.
    let cv = load_capture_verified(store, run)?;
    let cap = &cv.capture;
    if body.court.id != cap.court
        || body.court.question != cap.court_spec.question
        || body.court.falsifier != cap.court_spec.falsifier
    {
        return Err(FrfError::new(format!(
            "receipt {id}: the court block does not match the captured court"
        )));
    }
    if body.court.semantic_identity != cap.court_semantic_identity {
        return Err(FrfError::new(format!(
            "receipt {id}: the court semantic identity does not match the capture"
        )));
    }
    let env = &cap.court_spec.admissibility_envelope;
    let rec_env = &body.court.admissibility_envelope;
    if rec_env.fixture_family != env.fixture_family
        || rec_env.platforms != env.platforms
        || rec_env.observables != env.observables
        || rec_env.normalizers != env.normalizers
        || rec_env.replay_scope != env.replay_scope
    {
        return Err(FrfError::new(format!(
            "receipt {id}: the admissibility envelope does not match the capture"
        )));
    }
    if body.authority.identity_hash != cap.authority_artifact.sha256
        || body.authority.interpreter != cap.authority_artifact.interpreter
        || body.authority.native_runtime != cap.authority_artifact.native_runtime
    {
        return Err(FrfError::new(format!(
            "receipt {id}: the authority artifact does not match the capture"
        )));
    }
    if body.candidate.identity_hash != cap.candidate_artifact.sha256
        || body.candidate.interpreter != cap.candidate_artifact.interpreter
        || body.candidate.native_runtime != cap.candidate_artifact.native_runtime
    {
        return Err(FrfError::new(format!(
            "receipt {id}: the candidate artifact does not match the capture"
        )));
    }
    // The ADMISSION RECORD the receipt cites is part of the evidence: the
    // label must resolve to an admitted record whose name/version/artifact
    // hash match the receipt's authority block exactly. The authority record
    // is label-addressed (no self-identity), so WITHOUT this binding a
    // substituted admission record (the label intact, the content swapped)
    // would flow into consumers silently — the graph-mutation sweep proved
    // it could: identity and derivation must be established before semantic
    // consumption, and the cited admission record is part of the derivation.
    {
        let authority_id = format!("{}-{}", body.authority.name, body.authority.version);
        let record = store.load_authority(&authority_id).map_err(|e| {
            FrfError::new(format!(
                "receipt {id}: the cited authority {authority_id} is not admitted here: {e}"
            ))
        })?;
        if record.name != body.authority.name
            || record.version != body.authority.version
            || record.id != authority_id
            || record.kind != body.authority.kind
            || format!("file:{}", record.path) != body.authority.provenance
            || record.executable_sha256 != body.authority.identity_hash
        {
            return Err(FrfError::new(format!(
                "receipt {id}: the cited admission record {authority_id} does not match the receipt's authority block (the label is a claim until the record rederives)"
            )));
        }
    }
    // The closure, when carried, must be self-authenticating; and an artifact
    // is EITHER a script (interpreter chain) OR a native ELF (runtime
    // closure) — never both, never neither (a native artifact that names no
    // runtime cannot claim what it loaded; a script's interpreter chain is
    // its binding).
    for (who, interpreter, native_runtime) in [
        (
            "authority",
            &body.authority.interpreter,
            &body.authority.native_runtime,
        ),
        (
            "candidate",
            &body.candidate.interpreter,
            &body.candidate.native_runtime,
        ),
    ] {
        if interpreter.is_some() && native_runtime.is_some() {
            return Err(FrfError::new(format!(
                "receipt {id}: the {who} artifact carries BOTH an interpreter chain and a native runtime closure — an artifact is a script OR a native ELF, never both"
            )));
        }
        if let Some(nr) = native_runtime {
            verify_runtime_closure(nr)?;
        }
    }
    if body.fixtures.len() != 1 {
        return Err(FrfError::new(format!(
            "receipt {id}: v0 receipts carry exactly one fixture"
        )));
    }
    let f = &body.fixtures[0];
    if f.id != cap.fixture || f.hash != cap.fixture_sha256 || f.arguments != cap.arguments {
        return Err(FrfError::new(format!(
            "receipt {id}: the fixture block does not match the capture"
        )));
    }
    if body.environment != cap.environment {
        return Err(FrfError::new(format!(
            "receipt {id}: the environment block does not match the capture (the receipt must never ask its own host what environment an old court ran under)"
        )));
    }
    if body.provenance != cap.provenance || body.comparator_semantics != cap.comparator_semantics {
        return Err(FrfError::new(format!(
            "receipt {id}: provenance or comparator semantics do not match the capture (both are bound at observation time, never reconstructed)"
        )));
    }
    if body.execution_profile != cap.execution_profile || body.capture_bounds != cap.capture_bounds
    {
        return Err(FrfError::new(format!(
            "receipt {id}: the execution profile or capture bounds do not match the capture (the harness contract is bound at observation time)"
        )));
    }
    if body.execution_context != cap.execution_context {
        return Err(FrfError::new(format!(
            "receipt {id}: the declared execution-context closure does not match the capture (the runtime context is bound at observation time, never reconstructed)"
        )));
    }
    for obs in &body.observables {
        ObservableId::parse(&obs.axis)?;
        // The comparator that served this axis decides what the raw hashes
        // are: an in-binary axis rederives its captured projections; an
        // externally served axis binds the exact invocation + result records
        // and its raw hashes are the canonical reference/candidate subtrees
        // of the preserved request.
        let implementation = cap
            .provenance
            .comparator_implementations
            .iter()
            .find(|i| i.id == obs.axis)
            .ok_or_else(|| {
                FrfError::new(format!(
                    "receipt {id}: observable {} has no comparator implementation in the capture",
                    obs.axis
                ))
            })?;
        match &implementation.artifact {
            None => {
                let builtin =
                    crate::comparators::BuiltinKind::from_id(&obs.axis).ok_or_else(|| {
                        FrfError::new(format!(
                        "receipt {id}: observable {} was served by no known in-binary comparator",
                        obs.axis
                    ))
                    })?;
                let hashes_ok = match builtin {
                    crate::comparators::BuiltinKind::Exit => {
                        obs.raw_reference_hash == cap.reference.exit_sha256
                            && obs.raw_candidate_hash == cap.candidate.exit_sha256
                    }
                    crate::comparators::BuiltinKind::Stderr => {
                        obs.raw_reference_hash == cap.reference.stderr_first_line_sha256
                            && obs.raw_candidate_hash == cap.candidate.stderr_first_line_sha256
                    }
                    crate::comparators::BuiltinKind::Stdout => {
                        obs.raw_reference_hash == cap.reference.stdout_first_line_sha256
                            && obs.raw_candidate_hash == cap.candidate.stdout_first_line_sha256
                    }
                    // The domain surfaces' raw observation: the produced
                    // tree's manifest hash, or the raw stdout stream's hash.
                    crate::comparators::BuiltinKind::Tree => {
                        let ref_h = cap
                            .reference
                            .produced
                            .as_ref()
                            .map(|p| p.manifest_sha256.as_str())
                            .unwrap_or("");
                        let cand_h = cap
                            .candidate
                            .produced
                            .as_ref()
                            .map(|p| p.manifest_sha256.as_str())
                            .unwrap_or("");
                        obs.raw_reference_hash == ref_h && obs.raw_candidate_hash == cand_h
                    }
                    crate::comparators::BuiltinKind::Bytes
                    | crate::comparators::BuiltinKind::Json => {
                        obs.raw_reference_hash == cap.reference.stdout_sha256
                            && obs.raw_candidate_hash == cap.candidate.stdout_sha256
                    }
                };
                if !hashes_ok {
                    return Err(FrfError::new(format!(
                        "receipt {id}: observable {} raw hashes do not match the capture",
                        obs.axis
                    )));
                }
                if obs.comparator_request.is_some() || obs.comparator_result.is_some() {
                    return Err(FrfError::new(format!(
                        "receipt {id}: in-binary observable {} must not bind comparator request/result records",
                        obs.axis
                    )));
                }
            }
            Some(_) => {
                let evidence = store.load_comparator_evidence(run, &obs.axis)?;
                if obs.comparator_request.as_deref()
                    != Some(evidence.invocation.request_cid.as_str())
                    || obs.comparator_result.as_deref() != Some(evidence.result.result_id.as_str())
                {
                    return Err(FrfError::new(format!(
                        "receipt {id}: observable {} does not bind the recorded comparator request/result records",
                        obs.axis
                    )));
                }
                let dir = store.comparator_dir(run, &obs.axis)?;
                let request_bytes = read_bytes(&dir.join("request.json"), "comparator request")?;
                let request_value = crate::canon::parse_strict(&request_bytes)?;
                let ref_h = host::sha256_bytes(
                    crate::canon::encode(&request_value["reference"])?.as_bytes(),
                );
                let cand_h = host::sha256_bytes(
                    crate::canon::encode(&request_value["candidate"])?.as_bytes(),
                );
                if obs.raw_reference_hash != ref_h || obs.raw_candidate_hash != cand_h {
                    return Err(FrfError::new(format!(
                        "receipt {id}: observable {} raw hashes do not match the canonical request subtrees",
                        obs.axis
                    )));
                }
            }
        }
    }

    // 4. Residuals: EXACTLY the run's residuals (same ids, same order — the
    //    emitter preserves capture order, so order is part of the protocol).
    let receipt_ids: Vec<&str> = body.residuals.iter().map(|r| r.id.as_str()).collect();
    let capture_ids: Vec<&str> = cap.residuals.iter().map(|s| s.as_str()).collect();
    if receipt_ids != capture_ids {
        return Err(FrfError::new(format!(
            "receipt {id}: the residual set does not match the run's captured residuals"
        )));
    }
    for res in &body.residuals {
        let record = store.load_residual(&res.id)?.into_inner();
        if record.run != run {
            return Err(FrfError::new(format!(
                "receipt {id}: residual {} belongs to run {}",
                res.id, record.run
            )));
        }
        if res.axis != record.axis.as_str()
            || res.kind != record.kind
            || res.raw_reference_hash != record.raw_reference_sha256
            || res.raw_candidate_hash != record.raw_candidate_sha256
        {
            return Err(FrfError::new(format!(
                "receipt {id}: residual {} does not derive from its record file",
                res.id
            )));
        }
        let fp = crate::semantics::residual_fingerprint(&record)?;
        if res.residual_fingerprint != fp {
            return Err(FrfError::new(format!(
                "receipt {id}: residual fingerprint of {} does not rederive",
                res.id
            )));
        }
        // The sign verifies against the evidence it PINNED: a repeated-run
        // sign names the exact ExecutionSeries snapshot it was derived from
        // and the verifier replays it (the series must exist, contain the
        // run, and its trajectory for the lineage must yield the recorded
        // drift/slew); a single-run sign is a snapshot of emit time and is
        // accepted as such — a later experiment referencing the same
        // content-addressed run does not rewrite an emitted receipt.
        verify_sign(store, &record, &res.sign)?;
        // Dispositions must be bound to the EXACT immutable event that
        // supplied them. `open` is the projection of no events — a receipt
        // snapshot may predate later events, so it needs no event, and it
        // must not claim one. Any other disposition must name an event in the
        // chain whose fields EXACTLY match the receipt's: the receipt points
        // at a node in the hash chain, it does not merely copy state.
        match res.disposition.as_str() {
            "open" => {
                if res.disposition_event_id.is_some() {
                    return Err(FrfError::new(format!(
                        "receipt {id}: open residual {} claims a disposition_event_id — open is the projection of no events",
                        res.id
                    )));
                }
            }
            _ => {
                let Some(eid) = &res.disposition_event_id else {
                    return Err(FrfError::new(format!(
                        "receipt {id}: residual {} disposition {:?} has no bound disposition_event_id — a disposition must be an event, not a copy",
                        res.id,
                        res.disposition
                    )));
                };
                let events = store.disposition_events(&res.id)?;
                let Some(event) = events.iter().find(|e| &e.event_id == eid) else {
                    return Err(FrfError::new(format!(
                        "receipt {id}: residual {} binds disposition_event_id {eid} but no such event exists in its hash chain",
                        res.id
                    )));
                };
                let closure_ok = match (&event.disposition, &res.closure_predicate) {
                    (
                        Disposition::Fixed {
                            closure_predicate, ..
                        },
                        Some(cp),
                    ) => closure_predicate == cp,
                    (Disposition::Fixed { .. }, None) => false,
                    (_, None) => true,
                    (_, Some(_)) => false,
                };
                let observation_ok = match (&event.disposition, &res.observation_run_id) {
                    (
                        Disposition::Nonreproduced {
                            observation_run_id, ..
                        },
                        Some(oid),
                    ) => observation_run_id == oid,
                    (Disposition::Nonreproduced { .. }, None) => false,
                    (_, None) => true,
                    (_, Some(_)) => false,
                };
                let trajectory_ok = match (&event.disposition, &res.trajectory_id) {
                    (Disposition::Stabilized { trajectory_id, .. }, Some(tid)) => {
                        trajectory_id == tid
                    }
                    (Disposition::Stabilized { .. }, None) => false,
                    (_, None) => true,
                    (_, Some(_)) => false,
                };
                let stabilized_ok = match &event.disposition {
                    Disposition::Stabilized {
                        consecutive_passes,
                        stabilization_bound,
                        ..
                    } => {
                        res.consecutive_passes.as_deref() == Some(consecutive_passes.as_str())
                            && res.stabilization_bound.as_deref()
                                == Some(stabilization_bound.as_str())
                    }
                    _ => res.consecutive_passes.is_none() && res.stabilization_bound.is_none(),
                };
                if event.disposition.as_str() != res.disposition
                    || event.disposition.reason().map(str::to_string) != res.reason
                    || event.disposition.resolution_run_id().map(str::to_string)
                        != res.resolution_run_id
                    || event.disposition.observation_run_id().map(str::to_string)
                        != res.observation_run_id
                    || event.disposition.trajectory_id().map(str::to_string) != res.trajectory_id
                    || !closure_ok
                    || !observation_ok
                    || !trajectory_ok
                    || !stabilized_ok
                {
                    return Err(FrfError::new(format!(
                        "receipt {id}: residual {} disposition {:?} does not match the bound event {eid} — the receipt must not drift from the event it points at",
                        res.id,
                        res.disposition
                    )));
                }
            }
        }
        // The endoduction token rederives from the record under the receipt's
        // disposition (a snapshot, since receipts bind the state at emit time).
        let disposition = disposition_of(res).ok_or_else(|| {
            FrfError::new(format!(
                "receipt {id}: cannot rebuild the disposition of {}",
                res.id
            ))
        })?;
        let token = kappa::kappa(&record, &disposition);
        let recorded = body
            .endoduction
            .tokens
            .iter()
            .find(|t| t.residual_id == res.id)
            .ok_or_else(|| FrfError::new(format!("receipt {id}: no token bound for {}", res.id)))?;
        if token.token != recorded.token
            || token.next_court != recorded.next_court
            || token.blocks_claims != recorded.blocks_claims
        {
            return Err(FrfError::new(format!(
                "receipt {id}: the endoduction token of {} does not rederive",
                res.id
            )));
        }
    }

    // 5. Evidence-bearing closures must be backed by verifiable evidence:
    //    - `fixed` requires a resolution run under the SAME question/envelope
    //      whose axis closes, AND a CHANGED candidate artifact (a pass on the
    //      same candidate is a non-reproduction, not a fix);
    //    - `nonreproduced` requires a resolution-comparable observation run
    //      whose axis closes under the SAME candidate;
    //    - `stabilized` requires a verified trajectory whose tail establishes
    //      the declared consecutive non-reproductions under the SAME
    //      candidate.
    for res in &body.residuals {
        let axis = match ObservableId::parse(&res.axis) {
            Ok(a) => a,
            Err(_) => continue, // an undeclared/invalid axis is refused by validate_semantics
        };
        // The residual record (verified) drives the lineage / candidate
        // comparisons of its evidence-bearing closure.
        let Ok(record) = store.load_residual(&res.id).map(|u| u.into_inner()) else {
            continue; // refused by the residual loop above
        };
        match res.disposition.as_str() {
            "fixed" => {
                let Some(resolution_run_id) = &res.resolution_run_id else {
                    continue; // refused by validate_semantics
                };
                if resolution_run_id == run {
                    return Err(FrfError::new(format!(
                        "receipt {id}: residual {} claims to be fixed by the run that observed it — a disposition must not substitute for new evidence",
                        res.id
                    )));
                }
                store
                    .resolution_compatibility(run, resolution_run_id, &axis)
                    .map_err(|e| {
                        FrfError::new(format!(
                            "receipt {id}: the fixed closure of {} is not backed by verifiable resolution evidence: {e}",
                            res.id
                        ))
                    })?;
                store.require_fix_candidate_change(run, resolution_run_id).map_err(|e| {
                    FrfError::new(format!(
                        "receipt {id}: the fixed closure of {} is not backed by a changed candidate artifact: {e}",
                        res.id
                    ))
                })?;
            }
            "nonreproduced" => {
                let Some(observation_run_id) = &res.observation_run_id else {
                    continue; // refused by validate_semantics
                };
                if observation_run_id == run {
                    return Err(FrfError::new(format!(
                        "receipt {id}: residual {} claims to be nonreproduced by the run that observed it — a disposition must not substitute for new evidence",
                        res.id
                    )));
                }
                store
                    .resolution_compatibility(run, observation_run_id, &axis)
                    .map_err(|e| {
                        FrfError::new(format!(
                            "receipt {id}: the nonreproduced closure of {} is not backed by a verifiable observation run: {e}",
                            res.id
                        ))
                    })?;
                store.require_same_candidate(run, observation_run_id).map_err(|e| {
                    FrfError::new(format!(
                        "receipt {id}: the nonreproduced closure of {} changed the candidate — a candidate change is a fix, not a non-reproduction: {e}",
                        res.id
                    ))
                })?;
            }
            "stabilized" => {
                let Some(trajectory_id) = &res.trajectory_id else {
                    continue; // refused by validate_semantics
                };
                let Some(passes) = &res.consecutive_passes else {
                    continue; // refused by validate_semantics
                };
                store
                    .require_stabilization_trajectory(&record, trajectory_id, passes)
                    .map_err(|e| {
                        FrfError::new(format!(
                            "receipt {id}: the stabilized closure of {} is not backed by verifiable trajectory evidence: {e}",
                            res.id
                        ))
                    })?;
            }
            _ => {}
        }
    }

    Ok(ReceiptVerified {
        id: id.to_string(),
        body,
        detached: cv.detached,
    })
}

