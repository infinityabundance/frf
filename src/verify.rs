/// Verify one content-addressed reference for GRAPH verification: present
/// bytes are verified (corruption refused); a declared-detached CID (in
/// detached-objects.json) records the closure gap and passes — the graph
/// verifies, the object closure is incomplete-by-policy; a missing,
/// undeclared object is an incomplete or corrupt publication and is refused.
fn check_object(
    store: &Store,
    sha256: &str,
    detached: &mut Vec<crate::model::DetachedObjectRef>,
) -> Result<()> {
    match store.object_availability(sha256)? {
        crate::store::ObjectAvailability::Present => Ok(()),
        crate::store::ObjectAvailability::DeclaredDetached => {
            if let Some(entry) = store.detached_entry(sha256)? {
                if !detached.contains(&entry) {
                    detached.push(entry);
                }
            }
            Ok(())
        }
        crate::store::ObjectAvailability::Missing => Err(FrfError::new(format!(
            "object {} is missing and not declared detached — the evidence tree is incomplete",
            &sha256[..16]
        ))),
    }
}

/// A capture whose identity and derivation have been verified. Produced only
/// by [`load_capture_verified`].
pub struct CaptureVerified {
    pub run: String,
    pub capture: CaptureManifest,
    /// Content addresses the publication declared detached
    /// (detached-objects.json; bytes withheld by policy): the GRAPH
    /// verified, the object closure is incomplete-by-policy. Empty when the
    /// closure is complete.
    pub detached: Vec<crate::model::DetachedObjectRef>,
}

/// Load + verify ONE withheld-stream disposition record
/// (`<side>.<stream>.pub.json`, written by `publish-detached` where the
/// withheld bytes used to live): strict canonical JSON (duplicate property
/// names and non-canonical bytes refused — the same discipline as every
/// evidence document), the closed schema, and the POSITION-BOUND contract: a
/// disposition record names its own position (side + stream), the capture
/// surface's declared policy, and the EXACT bytes the capture recorded. A
/// record cannot move, cannot claim a different policy, and cannot name
/// different bytes — a withheld stream cannot silently disappear or change
/// what it withholds.
pub fn load_stream_publication_verified(
    store: &Store,
    dir: &Path,
    side: &str,
    stream: &str,
    recorded_sha: &str,
    expected_policy: &str,
) -> Result<crate::model::StreamPublicationRecord> {
    let disp_path = dir.join(format!("{side}.{stream}.pub.json"));
    let record: crate::model::StreamPublicationRecord =
        store.parse_evidence(&disp_path).map_err(|e| {
            FrfError::new(format!(
                "{} is not a canonical stream-publication record: {e}",
                disp_path.display()
            ))
        })?;
    if record.schema_version != crate::model::SCHEMA_STREAM_PUBLICATION {
        return Err(FrfError::new(format!(
            "{} has an unsupported schema {:?}",
            disp_path.display(),
            record.schema_version
        )));
    }
    if record.side != side || record.stream != stream {
        return Err(FrfError::new(format!(
            "{} names {}:{} — a disposition record cannot move",
            disp_path.display(),
            record.side,
            record.stream
        )));
    }
    if record.policy != expected_policy {
        return Err(FrfError::new(format!(
            "{} policy {:?} does not match the declared surface policy {:?}",
            disp_path.display(),
            record.policy,
            expected_policy
        )));
    }
    if record.sha256 != recorded_sha {
        return Err(FrfError::new(format!(
            "{} names bytes {} that do not hash to the recorded {} — the withheld stream's identity is broken",
            disp_path.display(),
            &record.sha256[..16.min(record.sha256.len())],
            &recorded_sha[..16.min(recorded_sha.len())]
        )));
    }
    Ok(record)
}

/// The publication manifest is a PROOF-DERIVED TRANSFORM RECORD, not merely
/// a valid document: derive the expected manifest from (a) every VERIFIED
/// capture in this store, (b) every capture-surface declaration, and (c) the
/// ACTUAL publication tree — a stream's `published` flag is the tree's own
/// state (its bytes exist, or a withholding disposition record took their
/// place; the verified capture loader has already proved that combination is
/// exactly the declared policy's — a missing stream without a declared
/// withholding policy, or a withheld stream without its disposition record,
/// refuses the capture). Exact equality with the recorded manifest is then
/// the transform's truth: an entry whose policy, hash, or publication state
/// lies is refused.
pub fn derive_publication_manifest(store: &Store) -> Result<crate::model::PublicationManifest> {
    use crate::model::{PublicationManifest, StreamDisposition};
    let mut streams: Vec<StreamDisposition> = Vec::new();
    let captures_dir = store.root.join("captures");
    if captures_dir.is_dir() {
        let mut runs: Vec<String> = std::fs::read_dir(&captures_dir)
            .map_err(|e| FrfError::new(format!("cannot read {}: {e}", captures_dir.display())))?
            .filter_map(|e| e.ok())
            .filter(|e| e.file_type().map(|t| t.is_dir()).unwrap_or(false))
            .map(|e| e.file_name().to_string_lossy().to_string())
            // Dot-prefixed entries are staging trees, not runs.
            .filter(|n| !n.starts_with('.'))
            .collect();
        runs.sort();
        for run in runs {
            let capture = &load_capture_verified(store, &run)?.capture;
            let dir = store.run_dir(&run)?;
            let policy_for = |side: &str, stream: &str| -> String {
                capture
                    .publication_surface
                    .as_ref()
                    .and_then(|v| {
                        v.iter()
                            .find(|p| p.side == side && p.stream == stream)
                            .map(|p| p.policy.clone())
                    })
                    .unwrap_or_else(|| "inline".to_string())
            };
            for (side, s) in [
                ("reference", &capture.reference),
                ("candidate", &capture.candidate),
            ] {
                for (stream, sha) in [("stdout", &s.stdout_sha256), ("stderr", &s.stderr_sha256)] {
                    let published = dir.join(format!("{side}.{stream}")).is_file();
                    streams.push(StreamDisposition {
                        run: run.clone(),
                        side: side.to_string(),
                        stream: stream.to_string(),
                        policy: policy_for(side, stream),
                        sha256: sha.clone(),
                        published,
                    });
                }
            }
        }
    }
    streams.sort_by(|a, b| (&a.run, &a.side, &a.stream).cmp(&(&b.run, &b.side, &b.stream)));
    Ok(PublicationManifest {
        schema_version: crate::model::SCHEMA_PUBLICATION_MANIFEST.to_string(),
        streams,
    })
}

/// Load + verify the publication manifest (`publication-manifest.json`, written
/// by `publish-detached`): strict canonical JSON (duplicate property names and
/// non-canonical bytes refused — the same discipline as every evidence
/// document), the closed schema, the cross-references (every stream
/// disposition must name a run that EXISTS in this store, and the
/// (run, side, stream) triple is unique), AND the EXACT DERIVATION: the
/// recorded manifest must EQUAL the manifest rederived from all verified
/// captures, all capture-surface declarations, and the actual publication
/// tree ([`derive_publication_manifest`]) — a manifest that is valid but
/// lies about a stream's policy, hash, or publication state is not the
/// transform's record. Absent when the store is not a publication.
pub fn load_publication_manifest_verified(
    store: &Store,
) -> Result<Option<crate::model::PublicationManifest>> {
    let path = store.root.join("publication-manifest.json");
    if !path.is_file() {
        return Ok(None);
    }
    let manifest: crate::model::PublicationManifest = store.parse_evidence(&path).map_err(|e| {
        FrfError::new(format!(
            "the publication manifest {} is not canonical evidence: {e}",
            path.display()
        ))
    })?;
    if manifest.schema_version != crate::model::SCHEMA_PUBLICATION_MANIFEST {
        return Err(FrfError::new(format!(
            "the publication manifest has an unsupported schema {:?}",
            manifest.schema_version
        )));
    }
    let mut seen: std::collections::BTreeSet<(String, String, String)> =
        std::collections::BTreeSet::new();
    for d in &manifest.streams {
        let key = (d.run.clone(), d.side.clone(), d.stream.clone());
        if !seen.insert(key.clone()) {
            return Err(FrfError::new(format!(
                "the publication manifest records the stream {}:{} of run {} TWICE — a stream has exactly one disposition",
                d.side,
                d.stream,
                &d.run[..16.min(d.run.len())]
            )));
        }
        let run_dir = store.run_dir(&d.run)?;
        if !run_dir.is_dir() {
            return Err(FrfError::new(format!(
                "the publication manifest names run {} which does not exist in this store — a disposition cannot invent an observation",
                &d.run[..16.min(d.run.len())]
            )));
        }
    }
    // THE EXACT DERIVATION: the recorded manifest must be the transform's
    // proof-derived record — exact equality with the rederived manifest, and
    // a first-difference report that names the lying entry.
    let expected = derive_publication_manifest(store)?;
    if expected != manifest {
        let mut i = 0;
        let detail = loop {
            let recorded = manifest.streams.get(i);
            let derived = expected.streams.get(i);
            if recorded != derived {
                break match (recorded, derived) {
                    (Some(r), Some(d))
                        if r.run == d.run && r.side == d.side && r.stream == d.stream =>
                    {
                        format!(
                            "stream {}:{} of run {}: recorded {{policy={},sha256={},published={}}} but the transform derives {{policy={},sha256={},published={}}}",
                            r.side,
                            r.stream,
                            &r.run[..16.min(r.run.len())],
                            r.policy,
                            &r.sha256[..16],
                            r.published,
                            d.policy,
                            &d.sha256[..16],
                            d.published
                        )
                    }
                    (Some(r), None) => format!(
                        "stream {}:{} of run {} is recorded but the transform derives no such stream — the manifest invents an observation",
                        r.side, r.stream, &r.run[..16.min(r.run.len())]
                    ),
                    (None, Some(d)) => format!(
                        "stream {}:{} of run {} is MISSING from the manifest — the transform derived it from the captures",
                        d.side, d.stream, &d.run[..16.min(d.run.len())]
                    ),
                    (Some(r), Some(d)) => format!(
                        "the recorded manifest and the derived transform disagree at the stream {}:{} of run {} (recorded run {}) vs (derived run {})",
                        r.side,
                        r.stream,
                        &r.run[..16.min(r.run.len())],
                        &r.run[..16.min(r.run.len())],
                        &d.run[..16.min(d.run.len())]
                    ),
                    (None, None) => unreachable!(),
                };
            }
            i += 1;
        };
        return Err(FrfError::new(format!(
            "the publication manifest is not the proof-derived transform record: {detail} — the manifest must EQUAL the rederived record of every verified capture's streams, declared surface policies, and actual publication state"
        )));
    }
    Ok(Some(manifest))
}

impl CaptureVerified {
    /// The run identity DIGEST (the hash component of the run id), recomputed
    /// from the capture's own recorded fields — the same function the court
    /// uses. The name is a claim until recomputed.
    pub fn digest(&self, residuals: &[ResidualRecord]) -> Result<String> {
        capture_digest(&self.capture, residuals)
    }
}

/// Recompute the run identity digest of a capture from its own recorded
/// fields (the ONE identity function, shared with the court and replay).
pub fn capture_digest(capture: &CaptureManifest, residuals: &[ResidualRecord]) -> Result<String> {
    let pre = RunPreimage {
        court: &capture.court,
        authority: &capture.authority,
        authority_interpreter: capture
            .authority_artifact
            .interpreter
            .as_ref()
            .map(|i| i.downstream_interpreter.sha256.as_str()),
        candidate_sha256: &capture.candidate_artifact.sha256,
        candidate_interpreter: capture
            .candidate_artifact
            .interpreter
            .as_ref()
            .map(|i| i.downstream_interpreter.sha256.as_str()),
        fixture_sha256: &capture.fixture_sha256,
        arguments: &capture.arguments,
        environment_digest: &capture.environment.digest,
        runner_hash: &capture.provenance.runner.frf_executable_hash,
        court_semantic_identity: &capture.court_semantic_identity,
        reference: &capture.reference,
        candidate: &capture.candidate,
        residuals,
        execution_profile: &capture.execution_profile,
        capture_bounds: &capture.capture_bounds,
        comparator_implementations: &capture.provenance.comparator_implementations,
        normalizer_implementations: &capture.provenance.normalizer_implementations,
        adapter_implementations: &capture.provenance.adapter_implementations,
        minimizer_implementations: &capture.provenance.minimizer_implementations,
        container_image: capture.container_image.as_ref(),
        publication_surface: capture.publication_surface.as_deref(),
    };
    crate::semantics::run_identity(&pre)
}

/// Recompute a capture's recorded `observation_identity` / `execution_identity`
/// fields from its own recorded fields — the same functions the court uses.
pub fn capture_identities(
    capture: &CaptureManifest,
    residuals: &[ResidualRecord],
) -> Result<(String, String)> {
    let pre = RunPreimage {
        court: &capture.court,
        authority: &capture.authority,
        authority_interpreter: capture
            .authority_artifact
            .interpreter
            .as_ref()
            .map(|i| i.downstream_interpreter.sha256.as_str()),
        candidate_sha256: &capture.candidate_artifact.sha256,
        candidate_interpreter: capture
            .candidate_artifact
            .interpreter
            .as_ref()
            .map(|i| i.downstream_interpreter.sha256.as_str()),
        fixture_sha256: &capture.fixture_sha256,
        arguments: &capture.arguments,
        environment_digest: &capture.environment.digest,
        runner_hash: &capture.provenance.runner.frf_executable_hash,
        court_semantic_identity: &capture.court_semantic_identity,
        reference: &capture.reference,
        candidate: &capture.candidate,
        residuals,
        execution_profile: &capture.execution_profile,
        capture_bounds: &capture.capture_bounds,
        comparator_implementations: &capture.provenance.comparator_implementations,
        normalizer_implementations: &capture.provenance.normalizer_implementations,
        adapter_implementations: &capture.provenance.adapter_implementations,
        minimizer_implementations: &capture.provenance.minimizer_implementations,
        container_image: capture.container_image.as_ref(),
        publication_surface: capture.publication_surface.as_deref(),
    };
    Ok((
        crate::semantics::observation_identity(&pre)?,
        crate::semantics::execution_identity(&pre)?,
    ))
}

fn read_bytes(path: &Path, what: &str) -> Result<Vec<u8>> {
    fs::read(path).map_err(|e| FrfError::new(format!("cannot read {what} {}: {e}", path.display())))
}

fn first_line(bytes: &[u8]) -> String {
    String::from_utf8_lossy(bytes)
        .split('\n')
        .next()
        .unwrap_or("")
        .to_string()
}

/// Verify a capture before anything may consume it:
///
/// 1. the run field inside `capture.yaml` equals the directory name (the name
///    is a claim until recomputed);
/// 2. every listed residual exists, is immutable, and belongs to this run;
/// 3. the run identity REDERIVES: `semantics::run_identity` over the
///    capture's own recorded fields hashes to the run id;
/// 4. the raw side files under the run dir rehash to the recorded hashes and
///    their first lines rederive;
/// 5. the authority/candidate/fixture snapshots exist and are
///    content-addressed (`verified_object_bytes` refuses corrupt objects).
pub fn load_capture_verified(store: &Store, run: &str) -> Result<CaptureVerified> {
    let mut capture = store.load_capture(run)?.into_inner();
    if capture.run != run {
        return Err(FrfError::new(format!(
            "capture {run}: the run field inside capture.json is {capture:?} — the name is a claim; refusing to consume"
        )));
    }

    let mut residuals = Vec::with_capacity(capture.residuals.len());
    for id in &capture.residuals {
        let record = store
            .load_residual(id)
            .map_err(|e| {
                FrfError::new(format!(
                    "capture {run}: listed residual {id} is missing: {e}"
                ))
            })?
            .into_inner();
        if record.run != run {
            return Err(FrfError::new(format!(
                "capture {run}: residual {id} belongs to run {}; the capture is not self-consistent",
                record.run
            )));
        }
        residuals.push(record);
    }

    // v15: the recorded harness events (a bound that fired during THIS run's
    // observation and completed as a valid side outcome — today the CPU
    // limit's SIGXCPU). Each cited record must exist, be canonical and
    // self-authenticating (the id rederives from its own fields), and belong
    // to this capture's court — a capture that cites missing, corrupt, or
    // foreign enforcement evidence is not self-consistent.
    for id in &capture.harness_events {
        let event = store.load_harness_event(id).map_err(|e| {
            FrfError::new(format!(
                "capture {run}: cited harness event {id} is missing or corrupt: {e}"
            ))
        })?;
        if event.court != capture.court {
            return Err(FrfError::new(format!(
                "capture {run}: cited harness event {id} belongs to court {}; the capture is not self-consistent",
                event.court
            )));
        }
    }

    // 3. The observation + execution identities rederive from the recorded
    //    fields, and the run identity composes them.
    let (obs, exec) = capture_identities(&capture, &residuals)?;
    if capture.observation_identity != obs {
        return Err(FrfError::new(format!(
            "capture {run}: the recorded observation_identity does not rederive from the recorded fields ({} != {}) — the capture is not self-authenticating",
            &obs[..16],
            &capture.observation_identity[..16]
        )));
    }
    if capture.execution_identity != exec {
        return Err(FrfError::new(format!(
            "capture {run}: the recorded execution_identity does not rederive from the recorded fields ({} != {}) — the capture is not self-authenticating",
            &exec[..16],
            &capture.execution_identity[..16]
        )));
    }
    let rederived = capture_digest(&capture, &residuals)?;
    // The run id is `run-{court}-{hash}`; the rederived hash must be its
    // digest component — the name is a claim until recomputed.
    let expected = format!("run-{}-{}", capture.court, rederived);
    if expected != capture.run {
        return Err(FrfError::new(format!(
            "capture {run}: the recorded fields do not hash to the run identity ({} != {}) — the capture is not self-authenticating",
            &rederived[..16],
            &capture.run[..16]
        )));
    }

    // 4. The raw side files derive the recorded hashes. A stream the
    //    capture's surface declares non-publishable (`hash-only`/`detached`)
    //    may be ABSENT — withheld by the publication transform; its
    //    disposition record must then exist, parse, carry the same policy,
    //    and name the same bytes. A missing stream WITHOUT a declared
    //    withholding policy is refused, and a withheld stream without its
    //    disposition record is refused: a withheld stream cannot silently
    //    disappear.
    let surface_policy = |side: &str, stream: &str| -> Option<String> {
        capture.publication_surface.as_ref().and_then(|v| {
            v.iter()
                .find(|p| p.side == side && p.stream == stream)
                .map(|p| p.policy.clone())
        })
    };
    let read_stream = |dir: &Path,
                       side: &str,
                       stream: &str,
                       recorded_sha: &str|
     -> Result<Option<Vec<u8>>> {
        let path = dir.join(format!("{side}.{stream}"));
        match fs::read(&path) {
            Ok(bytes) => Ok(Some(bytes)),
            Err(_) => {
                let policy = surface_policy(side, stream);
                if !matches!(policy.as_deref(), Some("hash-only") | Some("detached")) {
                    return Err(FrfError::new(format!(
                        "capture {run}: cannot read {side}.{stream} and no capture-surface policy withholds it"
                    )));
                }
                let record = load_stream_publication_verified(
                    store,
                    dir,
                    side,
                    stream,
                    recorded_sha,
                    policy.as_deref().unwrap_or_default(),
                )
                .map_err(|e| FrfError::new(format!("capture {run}: {e}")))?;
                // The verified record's checks (position, policy, bytes) all
                // held; the withheld stream's identity is intact.
                let _ = record;
                Ok(None)
            }
        }
    };
    let dir = store.run_dir(run)?;
    for (side, s) in [
        ("reference", &mut capture.reference),
        ("candidate", &mut capture.candidate),
    ] {
        let stdout = read_stream(&dir, side, "stdout", &s.stdout_sha256)?;
        let stderr = read_stream(&dir, side, "stderr", &s.stderr_sha256)?;
        // The domain comparators (structured.state) parse the raw COMPARED
        // bytes, which the serialized capture carries only as a hash. The
        // verified loader re-materializes the exact bytes it just rehashed:
        // verification never executes, it makes the ONE comparison relation
        // re-runnable over the verified capture (the residual verifier
        // re-derives the observed divergences from these bytes). A withheld
        // stream's identity is authenticated by its disposition record
        // above; present bytes must derive the recorded hashes.
        if let Some(bytes) = &stdout {
            s.stdout_bytes = bytes.clone();
            if host::sha256_bytes(bytes) != s.stdout_sha256 {
                return Err(FrfError::new(format!(
                    "capture {run}: {side}.stdout does not hash to the recorded value"
                )));
            }
            if first_line(bytes) != s.stdout_first_line {
                return Err(FrfError::new(format!(
                    "capture {run}: {side}.stdout first line does not derive to the recorded projection"
                )));
            }
        }
        if let Some(bytes) = &stderr {
            if host::sha256_bytes(bytes) != s.stderr_sha256 {
                return Err(FrfError::new(format!(
                    "capture {run}: {side}.stderr does not hash to the recorded value"
                )));
            }
            if first_line(bytes) != s.stderr_first_line {
                return Err(FrfError::new(format!(
                    "capture {run}: {side}.stderr first line does not derive to the recorded projection"
                )));
            }
        }
        let exit = read_bytes(&dir.join(format!("{side}.exit.txt")), "side file")?;
        if exit.trim_ascii() != s.exit.as_bytes()
            || host::sha256_bytes(s.exit.as_bytes()) != s.exit_sha256
        {
            return Err(FrfError::new(format!(
                "capture {run}: {side}.exit.txt does not derive to the recorded exit projection"
            )));
        }
        for (file, recorded, hash) in [
            (
                format!("{side}.stderr_first_line.txt"),
                s.stderr_first_line.as_str(),
                &s.stderr_first_line_sha256,
            ),
            (
                format!("{side}.stdout_first_line.txt"),
                s.stdout_first_line.as_str(),
                &s.stdout_first_line_sha256,
            ),
        ] {
            let text = read_bytes(&dir.join(&file), "side file")?;
            if text.trim_ascii() != recorded.as_bytes() {
                return Err(FrfError::new(format!(
                    "capture {run}: {file} does not derive to the recorded first-line projection"
                )));
            }
            if host::sha256_bytes(recorded.as_bytes()) != *hash {
                return Err(FrfError::new(format!(
                    "capture {run}: first-line hash for {file} does not rederive"
                )));
            }
        }
    }

    // 5. The content-addressed snapshots exist and are intact (a declared-
    //    detached payload verifies the GRAPH; the closure is recorded).
    let mut detached: Vec<crate::model::DetachedObjectRef> = Vec::new();
    check_object(store, &capture.authority_artifact.sha256, &mut detached)?;
    check_object(store, &capture.candidate_artifact.sha256, &mut detached)?;
    check_object(store, &capture.fixture_sha256, &mut detached)?;

    // 5b. The extension instrument snapshots exist and are intact: every
    //     normalizer, capture adapter, and minimizer implementation the
    //     capture bound at observation time is a content-addressed object.
    for impl_ in &capture.provenance.normalizer_implementations {
        if let Some(artifact) = &impl_.artifact {
            check_object(store, &artifact.sha256, &mut detached)?;
        }
    }
    for impl_ in &capture.provenance.adapter_implementations {
        if let Some(artifact) = &impl_.artifact {
            check_object(store, &artifact.sha256, &mut detached)?;
        }
    }
    for impl_ in &capture.provenance.minimizer_implementations {
        if let Some(artifact) = &impl_.artifact {
            check_object(store, &artifact.sha256, &mut detached)?;
        }
    }

    // 5c2. The DECLARED execution-context closure (when the court declared
    //     one) is self-authenticating: its content address rederives from
    //     its own artifacts (FRF/EXECUTION-CONTEXT/v1 over the document
    //     minus the cid, sorted by path), every artifact names a protocol
    //     role, the closure is sorted, and every snapshotted artifact's
    //     bytes are content-addressed objects — a declared runtime
    //     dependency is bound to the exact bytes, never assumed.
    if let Some(closure) = &capture.execution_context {
        if closure.schema_version != SCHEMA_EXECUTION_CONTEXT {
            return Err(FrfError::new(format!(
                "capture {run}: the execution-context closure carries schema_version {:?}, expected {SCHEMA_EXECUTION_CONTEXT}",
                closure.schema_version
            )));
        }
        let rederived = crate::semantics::execution_context_identity(closure)?;
        if closure.cid != rederived {
            return Err(FrfError::new(format!(
                "capture {run}: the execution-context closure cid does not rederive ({} != {}) — the closure is not self-authenticating",
                &rederived[..16],
                &closure.cid[..16]
            )));
        }
        let mut prev: Option<&str> = None;
        for a in &closure.artifacts {
            if !matches!(
                a.role.as_str(),
                "child-executable" | "runtime-library" | "data"
            ) {
                return Err(FrfError::new(format!(
                    "capture {run}: execution-context artifact {} declares role {:?}; the protocol admits child-executable, runtime-library, or data",
                    a.path, a.role
                )));
            }
            if let Some(p) = prev {
                if p >= a.path.as_str() {
                    return Err(FrfError::new(format!(
                        "capture {run}: the execution-context artifacts are not strictly sorted by path ({} after {p})",
                        a.path
                    )));
                }
            }
            prev = Some(&a.path);
            store.verified_object_bytes(&a.sha256)?;
        }
    }

    // 5c. The normalizer chain: the COMPARED streams recorded in the capture
    //     derive from the recorded normalizer evidence. Each normalizer's
    //     preserved request carries the streams it received (base64); its
    //     result records the hashes of the streams it returned; the next
    //     normalizer's request must carry exactly those, and the last
    //     result's hashes must BE the capture's compared hashes. Verification
    //     never executes — the raw streams survive inside the first request
    //     document, and the chain is rehashed end to end.
    for side in ["reference", "candidate"] {
        let capture_side = if side == "reference" {
            &capture.reference
        } else {
            &capture.candidate
        };
        let mut incoming: Option<(String, String)> = None;
        for semantic in &capture.normalizer_semantics {
            let (inv, res) = store.load_normalizer_evidence(run, &semantic.id, side)?;
            if inv.normalizer_semantic_cid != semantic.specification_hash {
                return Err(FrfError::new(format!(
                    "capture {run}: normalizer {} invocation does not bind the recorded semantic identity",
                    semantic.id
                )));
            }
            let request_path = store
                .normalizer_dir(run, &semantic.id, side)?
                .join("request.json");
            let request_value = crate::canon::parse_strict(&read_bytes(&request_path, "request")?)?;
            let carried = (
                host::sha256_bytes(&crate::ext::unb64(
                    request_value["stdout_base64"].as_str().unwrap_or_default(),
                    "normalizer request stdout",
                )?),
                host::sha256_bytes(&crate::ext::unb64(
                    request_value["stderr_base64"].as_str().unwrap_or_default(),
                    "normalizer request stderr",
                )?),
            );
            if let Some((prev_stdout, prev_stderr)) = &incoming {
                if &carried.0 != prev_stdout || &carried.1 != prev_stderr {
                    return Err(FrfError::new(format!(
                        "capture {run}: the normalizer chain is broken — normalizer {} on the {side} side received streams that are not the previous result's output",
                        semantic.id
                    )));
                }
            }
            incoming = Some((res.stdout_sha256.clone(), res.stderr_sha256.clone()));
        }
        if let Some((stdout_sha256, stderr_sha256)) = &incoming {
            if stdout_sha256 != &capture_side.stdout_sha256
                || stderr_sha256 != &capture_side.stderr_sha256
            {
                return Err(FrfError::new(format!(
                    "capture {run}: the {side} side's recorded compared streams do not derive from the recorded normalizer chain"
                )));
            }
        }
    }

    // 5d. The capture-adapter evidence: for every adapted axis, the capture's
    //     adapted observation must BE the adapter's recorded output (its
    //     payload decodes to the recorded content hash), the adapter's
    //     request must have carried the truly raw outcome, and the invocation
    //     must bind the recorded semantic identity.
    for impl_ in &capture.provenance.adapter_implementations {
        let Some(_artifact) = &impl_.artifact else {
            continue;
        };
        let semantic = capture
            .adapter_semantics
            .iter()
            .find(|s| s.id == impl_.id)
            .ok_or_else(|| {
                FrfError::new(format!(
                    "capture {run}: capture adapter {} has no semantic in the capture",
                    impl_.id
                ))
            })?;
        for side in ["reference", "candidate"] {
            let (inv, res) = store.load_adapter_evidence(run, &impl_.id, side)?;
            if inv.adapter_semantic_cid != semantic.specification_hash {
                return Err(FrfError::new(format!(
                    "capture {run}: capture adapter {} invocation does not bind the recorded semantic identity",
                    impl_.id
                )));
            }
            let capture_side = if side == "reference" {
                &capture.reference
            } else {
                &capture.candidate
            };
            let recorded = capture_side.adapted.as_ref().ok_or_else(|| {
                FrfError::new(format!(
                    "capture {run}: the {side} side carries no adapted observation for adapted axis {}",
                    impl_.id
                ))
            })?;
            if recorded.content_sha256 != res.observation_sha256 {
                return Err(FrfError::new(format!(
                    "capture {run}: the {side} side's adapted observation for axis {} does not match the adapter's recorded result",
                    impl_.id
                )));
            }
            if host::sha256_bytes(&crate::ext::unb64(
                &recorded.payload_base64,
                "adapted observation payload",
            )?) != recorded.content_sha256
            {
                return Err(FrfError::new(format!(
                    "capture {run}: the {side} side's adapted payload for axis {} does not decode to its recorded content hash",
                    impl_.id
                )));
            }
            // The adapter was fed the truly raw outcome: its request's
            // carried streams must match the raw record — the side files when
            // no normalizers applied, else the first normalizer's request.
            let request_path = store
                .adapter_dir(run, &impl_.id, side)?
                .join("request.json");
            let request_value = crate::canon::parse_strict(&read_bytes(&request_path, "request")?)?;
            let carried = (
                host::sha256_bytes(&crate::ext::unb64(
                    request_value["outcome"]["stdout_base64"]
                        .as_str()
                        .unwrap_or_default(),
                    "adapter request stdout",
                )?),
                host::sha256_bytes(&crate::ext::unb64(
                    request_value["outcome"]["stderr_base64"]
                        .as_str()
                        .unwrap_or_default(),
                    "adapter request stderr",
                )?),
            );
            let raw: (String, String) = if capture.normalizer_semantics.is_empty() {
                let dir = store.run_dir(run)?;
                let stdout = read_bytes(&dir.join(format!("{side}.stdout")), "side file")?;
                let stderr = read_bytes(&dir.join(format!("{side}.stderr")), "side file")?;
                (host::sha256_bytes(&stdout), host::sha256_bytes(&stderr))
            } else {
                let first = &capture.normalizer_semantics[0];
                let first_request_path = store
                    .normalizer_dir(run, &first.id, side)?
                    .join("request.json");
                let first_request =
                    crate::canon::parse_strict(&read_bytes(&first_request_path, "request")?)?;
                (
                    host::sha256_bytes(&crate::ext::unb64(
                        first_request["stdout_base64"].as_str().unwrap_or_default(),
                        "first normalizer request stdout",
                    )?),
                    host::sha256_bytes(&crate::ext::unb64(
                        first_request["stderr_base64"].as_str().unwrap_or_default(),
                        "first normalizer request stderr",
                    )?),
                )
            };
            if carried.0 != raw.0 || carried.1 != raw.1 {
                return Err(FrfError::new(format!(
                    "capture {run}: the capture adapter for axis {} on the {side} side did not receive the truly raw outcome",
                    impl_.id
                )));
            }
        }
    }

    // 6. External comparator evidence: every externally served axis must have
    //    a verified invocation + result record bound to this run (identity
    //    rederives, request/response documents hash to their cids, the
    //    response names its request, the referenced residuals belong to the
    //    run), and the exact instrument bytes must be intact under objects/.
    for impl_ in &capture.provenance.comparator_implementations {
        if let Some(artifact) = &impl_.artifact {
            store.verified_object_bytes(&artifact.sha256)?;
            let evidence = store.load_comparator_evidence(run, &impl_.id)?;
            if evidence.invocation.axis.as_str() != impl_.id
                || evidence.invocation.comparator_semantic_cid
                    != capture
                        .comparator_semantics
                        .iter()
                        .find(|s| s.id == impl_.id)
                        .map(|s| s.specification_hash.clone())
                        .ok_or_else(|| {
                            FrfError::new(format!(
                                "capture {run}: externally served axis {} has no comparator semantic in the capture",
                                impl_.id
                            ))
                        })?
            {
                return Err(FrfError::new(format!(
                    "capture {run}: comparator invocation for axis {} does not bind the recorded semantic identity",
                    impl_.id
                )));
            }
        }
    }

    Ok(CaptureVerified {
        run: run.to_string(),
        capture,
        detached,
    })
}

