/// A residual whose identity AND derivation have been verified against its
/// parent run. Private fields: the only constructor is
/// [`load_residual_verified`], so a `ResidualVerified` cannot be fabricated —
/// a witness, receipt, or reducer that accepts only this type cannot be
/// pointed at a residual that does not derive from a verified observation.
///
/// Verification proves, in order:
///
/// 1. the residual document parses as strict canonical evidence;
/// 2. its parent capture verifies (run identity rederives, side files
///    rehash, every referenced object is intact);
/// 3. the residual belongs to the run and the run references it back
///    (same run, court, authority, and candidate artifact);
/// 4. its axis was DECLARED by the court's comparator semantics;
/// 5. the comparator result generated this exact divergence — an externally
///    served axis's content-addressed result names this residual id; a
///    built-in axis's divergence re-derives from the verified sides through
///    the ONE comparison relation, with the exact recorded surface and raw
///    projections;
/// 6. the raw projections rehash to the recorded hashes;
/// 7. the residual fingerprint rederives (it is computed fresh).
pub struct ResidualVerified {
    id: String,
    record: ResidualRecord,
    capture: CaptureVerified,
}

impl ResidualVerified {
    pub fn id(&self) -> &str {
        &self.id
    }

    pub fn record(&self) -> &ResidualRecord {
        &self.record
    }

    pub fn capture(&self) -> &CaptureVerified {
        &self.capture
    }
}

/// Verify a residual before anything may consume it (see [`ResidualVerified`]
/// for the proof order). The parent run is verified FIRST — a residual whose
/// run does not verify is refused before any field of the residual itself is
/// trusted.
pub fn load_residual_verified(store: &Store, id: &str) -> Result<ResidualVerified> {
    // 1. The document must parse as strict canonical evidence (the store
    //    loader refuses non-canonical bytes and duplicate property names).
    let record = store.load_residual(id)?.into_inner();

    // 2. The parent capture verifies: run identity rederives, side files
    //    rehash, snapshots + extension instruments are intact.
    let capture = load_capture_verified(store, &record.run)?;

    // 3. The residual belongs to the run, and the run references it back.
    if record.run != capture.run {
        return Err(FrfError::new(format!(
            "residual {id}: its recorded run {} does not match the verified parent {}",
            record.run, capture.run
        )));
    }
    if !capture.capture.residuals.iter().any(|rid| rid == id) {
        return Err(FrfError::new(format!(
            "residual {id}: the capture of run {} does not reference it — the residual is not an observation of that run",
            record.run
        )));
    }
    if record.court != capture.capture.court {
        return Err(FrfError::new(format!(
            "residual {id}: its court {} does not match the parent run's court {}",
            record.court, capture.capture.court
        )));
    }
    if record.authority != capture.capture.authority {
        return Err(FrfError::new(format!(
            "residual {id}: its authority {} does not match the parent run's authority {}",
            record.authority, capture.capture.authority
        )));
    }
    if record.candidate_sha256 != capture.capture.candidate_artifact.sha256 {
        return Err(FrfError::new(format!(
            "residual {id}: its candidate {} does not match the candidate the parent run executed {}",
            &record.candidate_sha256[..16],
            &capture.capture.candidate_artifact.sha256[..16]
        )));
    }

    // 4. The axis was declared by the court's comparator semantics (each
    //    declared observable is served by exactly one comparator).
    let semantic = capture
        .capture
        .comparator_semantics
        .iter()
        .find(|s| s.id == record.axis.as_str())
        .ok_or_else(|| {
            FrfError::new(format!(
                "residual {id}: axis {} was not declared by the court of run {}",
                record.axis.as_str(),
                record.run
            ))
        })?;
    // The divergence's KIND is fixed by the question: the comparator's
    // residual classifier must BE this record's kind.
    let expected_kind = ResidualKind::parse(&semantic.residual_classifier)?;
    if expected_kind != record.kind {
        return Err(FrfError::new(format!(
            "residual {id}: its kind {} does not match the axis's declared residual classifier {}",
            record.kind.as_str(),
            semantic.residual_classifier
        )));
    }

    // 5. The comparator result generated this exact divergence.
    let externally_served = capture
        .capture
        .provenance
        .comparator_implementations
        .iter()
        .any(|i| i.id == record.axis.as_str() && i.artifact.is_some());
    if externally_served {
        // The content-addressed result record (cross-verified: response
        // names its request, documents hash to their cids) names the exact
        // residual observations its invocation produced. Verification never
        // re-executes the comparator — the instrument's output is bound by
        // the result's content address.
        let evidence = store.load_comparator_evidence(&record.run, record.axis.as_str())?;
        if evidence.invocation.axis.as_str() != record.axis.as_str() {
            return Err(FrfError::new(format!(
                "residual {id}: the comparator invocation for axis {} is bound to a different axis",
                record.axis.as_str()
            )));
        }
        if !evidence
            .result
            .residual_observation_ids
            .iter()
            .any(|rid| rid == id)
        {
            return Err(FrfError::new(format!(
                "residual {id}: the comparator result for axis {} does not name this residual as its observation — the residual does not derive from the comparator that served the axis",
                record.axis.as_str()
            )));
        }
    } else {
        // The in-binary relation: re-derive the divergences from the
        // VERIFIED sides through the ONE comparison relation (the same
        // function the court dispatched to; `evaluate` on a built-in plan is
        // exactly this). The recorded surface + raw projections must be one
        // of the derived divergences — nothing else may decide parity.
        let kind = BuiltinKind::from_id(record.axis.as_str()).ok_or_else(|| {
            FrfError::new(format!(
                "residual {id}: axis {} was served by no known in-binary comparator",
                record.axis.as_str()
            ))
        })?;
        let outcome = kind.compare(&capture.capture.reference, &capture.capture.candidate)?;
        let derived = match outcome {
            ComparatorOutcome::Divergent(v) => v,
            _ => Vec::new(),
        };
        if !derived.iter().any(|(surface, raw_ref, raw_cand)| {
            surface.as_deref() == record.surface.as_deref()
                && raw_ref == &record.raw_reference
                && raw_cand == &record.raw_candidate
        }) {
            return Err(FrfError::new(format!(
                "residual {id}: the recorded divergence (axis {}, surface {:?}) does not rederive from the verified sides — the observation does not derive from the comparator that served the axis",
                record.axis.as_str(),
                record.surface
            )));
        }
    }

    // 6. The raw projections rehash to the recorded hashes.
    if record.raw_reference_sha256 != host::sha256_bytes(record.raw_reference.as_bytes()) {
        return Err(FrfError::new(format!(
            "residual {id}: raw_reference does not hash to the recorded reference hash"
        )));
    }
    if record.raw_candidate_sha256 != host::sha256_bytes(record.raw_candidate.as_bytes()) {
        return Err(FrfError::new(format!(
            "residual {id}: raw_candidate does not hash to the recorded candidate hash"
        )));
    }

    // 7. The fingerprint rederives (computed fresh; the semantic identity of
    //    the divergence — a witness binds THIS, never a caller-supplied
    //    address).
    crate::semantics::residual_fingerprint(&record)?;

    Ok(ResidualVerified {
        id: id.to_string(),
        record,
        capture,
    })
}

